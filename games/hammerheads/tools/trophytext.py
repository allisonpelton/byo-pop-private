#!/usr/bin/env python3
"""Writes games/hammerheads/src/TrophyText.inc: the names and the descriptions of the exe's twenty-one trophies.

The exe's static initialiser (0x54db80) builds two tables of std::string, the names at 0x591390 and the descriptions at 0x5915e0
(twenty-one of 0x1c bytes each), from string literals: each one is a "push <literal>; mov ecx, <element>; call 0x401800". They
are the game's own text, so the file is git-ignored (games/hammerheads/.gitignore): run this once in a new worktree, with the
unwrapped exe in re/hammerheads.

    python games/hammerheads/tools/trophytext.py            # writes src/TrophyText.inc
    python games/hammerheads/tools/trophytext.py --print    # only prints the two tables
"""
import os
import struct
import sys

import pe

IMAGE = pe.Image()
TABLES = [(0x591390, "TROPHY_NAMES"), (0x5915e0, "TROPHY_DESCRIPTIONS")]
COUNT = 21
ELEMENT_SIZE = 0x1c
INIT_START = 0x54db80
INIT_END = 0x54f000


def cstring(address):
    data = IMAGE.bytes(address, 128)
    return data.split(b"\0")[0].decode("latin1")


def read_tables():
    code = IMAGE.bytes(INIT_START, INIT_END - INIT_START)
    tables = {base: [None] * COUNT for base, _ in TABLES}
    for offset in range(len(code) - 5):
        if code[offset] != 0xB9:                       # mov ecx, imm32
            continue
        element = struct.unpack_from("<I", code, offset + 1)[0]
        for base, _ in TABLES:
            index, rest = divmod(element - base, ELEMENT_SIZE)
            if rest == 0 and 0 <= index < COUNT:
                # the literal is pushed shortly before the element's address is loaded
                for back in range(offset - 5, max(offset - 40, 0), -1):
                    if code[back] == 0x68:                # push imm32
                        pointer = struct.unpack_from("<I", code, back + 1)[0]
                        if 0x550000 <= pointer < 0x580000:
                            tables[base][index] = cstring(pointer)
                            break
    for base, _ in TABLES:
        assert None not in tables[base], "a trophy text was not found"
    return tables


def main():
    tables = read_tables()
    if "--print" in sys.argv:
        for base, name in TABLES:
            print(name, tables[base])
        return
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "TrophyText.inc")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/trophytext.py from the exe (0x591390, 0x5915e0). Not committed: the texts are the game's own.\n")
        for base, name in TABLES:
            f.write("static const char* const %s[%d] =\n{\n" % (name, COUNT))
            for text in tables[base]:
                f.write('\t"%s",\n' % text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\n"))
            f.write("};\n")
    print("wrote", os.path.abspath(out))


if __name__ == "__main__":
    main()
