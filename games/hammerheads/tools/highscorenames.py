#!/usr/bin/env python3
"""Writes games/hammerheads/src/HighScoreNames.inc: the names the exe's high score table starts with.

The exe's table constructor (0x456080) takes the default names of its twenty places from two lists of ten (the pointers at
0x592444 and 0x592470, their counts at 0x59246c and 0x592498). They are the game's own text, so the file is git-ignored
(games/hammerheads/.gitignore): run this once in a new worktree, with the unwrapped exe in re/hammerheads.

    python games/hammerheads/tools/highscorenames.py            # writes src/HighScoreNames.inc
    python games/hammerheads/tools/highscorenames.py --print    # only prints the two lists
"""
import os
import struct
import sys

import pe

IMAGE = pe.Image()
LISTS = [(0x592444, 0x59246c), (0x592470, 0x592498)]


def cstring(address):
    data = IMAGE.bytes(address, 64)
    return data.split(b"\0")[0].decode("latin1")


def read_list(array, count_address):
    count = struct.unpack("<I", IMAGE.bytes(count_address, 4))[0]
    names = []
    for index in range(count):
        pointer = struct.unpack("<I", IMAGE.bytes(array + 4 * index, 4))[0]
        names.append(cstring(pointer))
    return names


def main():
    lists = [read_list(array, count) for array, count in LISTS]
    if "--print" in sys.argv:
        for names in lists:
            print(names)
        return
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "HighScoreNames.inc")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/highscorenames.py from the exe (0x592444, 0x592470). Not committed: the names are the game's own text.\n")
        for number, names in enumerate(lists):
            f.write("static const char* const DEFAULT_NAMES_%s[%d] =\n{\n" % ("AB"[number], len(names)))
            for name in names:
                f.write('\t"%s",\n' % name.replace("\\", "\\\\").replace('"', '\\"'))
            f.write("};\n")
    print("wrote", os.path.abspath(out))


if __name__ == "__main__":
    main()
