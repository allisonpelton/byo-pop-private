#!/usr/bin/env python3
"""Writes src/Res.h and src/Res.cpp, the resource globals of Hammer Heads, as the exe's own generated code has them: a
global for every image, font and sound of properties/resources.xml (named by the group's idprefix and the resource's id,
IMAGE_CUBBY_BACK), and one Extract<Group>Resources function a group (0x426710 Game, 0x428fd0 Gui, 0x42c1f0 Init, 0x42c790
LoadingScreen, 0x42cb90 MainMenu) that looks each of its resources up in the resource manager and stores it.

The ids and the groups come from the file; games/hammerheads/docs/resglobals.txt (tools/resnames.py: the exe's own
globals, read from its machine code) is the cross-check: every id the exe's extraction code stores is in the file.

    python games/hammerheads/tools/resgen.py [--xml assets/hammerheads/properties/resources.xml]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
EXTRACT_ADDRESSES = {'Game': 0x426710, 'Gui': 0x428fd0, 'Init': 0x42c1f0, 'LoadingScreen': 0x42c790, 'MainMenu': 0x42cb90}
HEADER = ['// Generated by games/hammerheads/tools/resgen.py from properties/resources.xml: the resource globals and the',
          '// functions that fill them, as the exe\'s own generated code has them (0x426710-0x42d081). The ids are the names of',
          '// the resources in that file, with the group\'s id prefix.']
KINDS = {'Image': ('Image*', 'GetImageThrow'), 'Font': ('Font*', 'GetFontThrow'), 'Sound': ('int', 'GetSoundThrow')}


def read_groups(path):
    text = open(path, encoding='utf-8-sig', errors='replace').read()
    groups = []
    for m in re.finditer(r'<Resources\s+id="([^"]+)"\s*>(.*?)</Resources>', text, re.S):
        prefix = ''
        items = []
        for tag in re.finditer(r'<(SetDefaults|Image|Font|Sound)\b([^>]*?)/?>', m.group(2)):
            if tag.group(1) == 'SetDefaults':
                p = re.search(r'idprefix="([^"]*)"', tag.group(2))
                if p:
                    prefix = p.group(1)
            else:
                rid = re.search(r'\bid="([^"]+)"', tag.group(2)).group(1)
                items.append((tag.group(1), prefix + rid))
        groups.append((m.group(1), items))
    return groups


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--xml', default=os.path.join(ROOT, 'assets', 'hammerheads', 'properties', 'resources.xml'))
    args = ap.parse_args()
    groups = read_groups(args.xml)
    kind = {}
    for g, items in groups:
        for k, rid in items:
            if kind.setdefault(rid, k) != k:
                sys.exit('%s is both %s and %s' % (rid, kind[rid], k))
    known = os.path.join(ROOT, 'games', 'hammerheads', 'docs', 'resglobals.txt')
    if os.path.exists(known):
        in_exe = {line.split()[1] for line in open(known) if line.strip()}
        print('ids in the exe but not in the file:', sorted(in_exe - set(kind)))
        print('ids in the file but not stored by the exe:', sorted(set(kind) - in_exe))

    h = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class ResourceManager;', '']
    c = HEADER + ['#include "Res.h"', '', '#include "ResourceManager.h"', '', 'using namespace Sexy;', '']
    for g, items in groups:
        for k, rid in items:
            ctype = KINDS[k][0]
            h.append('extern %s %s;' % (ctype, rid))
            c.append('%s Sexy::%s = %s;' % (ctype, rid, '0' if ctype == 'int' else 'nullptr'))
    h.append('')
    c.append('')
    for g, items in groups:
        h.append('bool Extract%sResources(ResourceManager* theManager);' % g)
        address = EXTRACT_ADDRESSES.get(g)
        c.append('// 0x%x: the group "%s"' % (address, g) if address else '// the group "%s"' % g)
        c.append('bool Sexy::Extract%sResources(ResourceManager* theManager)' % g)
        c += ['{', '\ttry', '\t{']
        for k, rid in items:
            c.append('\t\t%s = theManager->%s("%s");' % (rid, KINDS[k][1], rid))
        c += ['\t}', '\tcatch (ResourceManagerException&)', '\t{', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
    h += ['', '}', '']
    open(os.path.join(SRC, 'Res.h'), 'w', newline='\n').write('\n'.join(h))
    open(os.path.join(SRC, 'Res.cpp'), 'w', newline='\n').write('\n'.join(c))
    print('%d ids in %d groups' % (len(kind), len(groups)))


if __name__ == '__main__':
    main()
