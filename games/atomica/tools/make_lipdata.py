#!/usr/bin/env python3
"""Generate games/atomica/src/LipDataTable.inc: where each voice's mouth data is in the exe.

Dr. Atomicus' mouth follows a short list of keyframes for each voice clip (Atomicus::Say and ::Comment give 0x40b1e0 the
address of one; 0x421c70 reads it): groups of three ints, ended by a group that starts with -1. Like the texts
(GameText.h) the port carries none of it: the table lists each list's address in the 2.52 game image, its length in ints
and a hash, and LoadGameTexts() reads the numbers from the player's own Atomica.exe.

    python games/atomica/tools/make_lipdata.py [--exe re/atomica/bin/Atomica.exe] [--out games/atomica/src/LipDataTable.inc]
"""
import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))

# The lists Atomicus::Say (0x40b5a0) and ::Comment (0x40c000) pass to 0x40b1e0
ADDRESSES = [0x4cb180, 0x4cb1c8, 0x4cb238, 0x4cb2a8, 0x4cb320, 0x4cb398, 0x4cb408, 0x4cb478, 0x4cb4c0, 0x4cb560,
             0x4cb618, 0x4cb9e8, 0x4cba28, 0x4cba70, 0x4cbaac, 0x4cbae8, 0x4cbb28, 0x4cbb98, 0x4cbbf8]


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + max(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "atomica", "bin", "Atomica.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "atomica", "src", "LipDataTable.inc"))
    args = ap.parse_args()
    d = open(args.exe, "rb").read()
    out = ["// Generated by games/atomica/tools/make_lipdata.py. Where the mouth data of each of Dr. Atomicus' voices is in",
           "// Atomica Deluxe 2.52's image: address, length in ints (the -1 that ends a list included) and FNV-1a hash.",
           "// The numbers are read from the player's own Atomica.exe at start-up (GameText.h); none are in the repository."]
    for va in ADDRESSES:
        o = va_to_off(d, va)
        n = 0
        while struct.unpack_from("<i", d, o + 12 * n)[0] != -1:
            n += 1
        size = 12 * n + 4
        out.append("LIPDATA(0x%08x, %d, 0x%08x)" % (va, size // 4, fnv1a(d[o:o + size])))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(ADDRESSES), args.out))


if __name__ == "__main__":
    sys.exit(main())
