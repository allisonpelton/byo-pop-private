#!/usr/bin/env python3
"""Generate games/atomica/src/GameTextTable.inc: where each of Atomica's hard-coded texts is in the exe.

The port carries no game text (games/atomica/src/GameText.h): it reads every text from the player's own
Atomica.exe by address. This finds those addresses. The input is Ghidra's string export of the game image
(re/atomica/gh/strings.jsonl, git-ignored: it holds game text); the output holds only addresses, lengths and
hashes. Every string between the game's first and last data string is listed, so a translation can name any
of them as GT(0xADDR).

    python games/atomica/tools/make_gametext.py [--strings re/atomica/gh/strings.jsonl] [--exe re/atomica/bin/Atomica.exe]
        [--out games/atomica/src/GameTextTable.inc]
"""
import argparse
import glob
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
FIRST = 0x4ae000   # the game's .rdata strings (between its vtables): resource names, texts, rank names
LAST = 0x4b3180


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + max(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strings", default=os.path.join(ROOT, "re", "atomica", "gh", "strings.jsonl"))
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "atomica", "bin", "Atomica.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "atomica", "src", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    rows = []
    for line in open(args.strings):
        j = json.loads(line)
        if j["type"] != "string":
            continue
        va = int(j["addr"], 16)
        if FIRST <= va < LAST:
            rows.append(va)
    # strings Ghidra did not mark (referenced as DAT_<address> in its decompilation of the game code)
    decomp = os.path.join(os.path.dirname(args.strings), "decomp")
    known = set(rows)
    if os.path.isdir(decomp):
        for path in glob.glob(os.path.join(decomp, "*", "*.c")):
            for m in re.finditer(r"DAT_(004[ab][0-9a-f]{4})", open(path, encoding="latin1").read()):
                va = int(m.group(1), 16)
                if FIRST <= va < LAST and va not in known:
                    try:
                        o = va_to_off(d, va)
                    except ValueError:
                        continue
                    e = d.index(bytes(1), o)
                    s = d[o:e]
                    if 1 <= len(s) < 200 and all(32 <= c < 127 or c in (9, 10, 13) for c in s):
                        rows.append(va)
                        known.add(va)
    # texts found in the disassembly (genhints.py): Ghidra's list lacks the short ones
    extra = os.path.join(HERE, "extra_strings.txt")
    if os.path.exists(extra):
        for line in open(extra):
            line = line.split("#")[0].strip()
            if line and int(line, 16) not in known:
                rows.append(int(line, 16))
                known.add(int(line, 16))
    rows.sort()
    out = ["// Generated by games/atomica/tools/make_gametext.py. Atomica Deluxe 2.52's hard-coded strings:",
           "// address in the game image, length and FNV-1a hash. The texts themselves are read from the",
           "// player's own Atomica.exe at start-up (GameText.h); none are in the repository."]
    for va in rows:
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(rows), args.out))


if __name__ == "__main__":
    sys.exit(main())
