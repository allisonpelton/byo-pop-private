#!/usr/bin/env python3
"""Writes games/rocketmania/src/HeadData.inc: the numbers the talking head and the hover tips read from the original's
data (RocketManiaGame 0x4c5270 moods, 0x4c4e10 tip regions, 0x4c4e80 tip places, 0x4c4eb8 tip frames, 0x4e57b0 and
0x4e5890 the addresses of the tip lines). No text: the lines are only addresses, which GT() resolves from the player's exe.

    python games/rocketmania/tools/make_headdata.py
"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ptrtable import d, off


def word(va):
    return struct.unpack_from('<i', d, off(va))[0]


MOODS = 23
out = []
out.append('// Generated by tools/make_headdata.py from the original\'s data tables: numbers and addresses only, no text.')
out.append('')
out.append('// 0x4c5270: for each mood the pairs (mouth, half the updates it lasts) up to a mouth of -1; the original')
out.append('// keeps 50 pairs for each mood. A mouth is one of the head pictures: 0 to 6 the seven mouths, 7 and 8 the turned heads.')
out.append('static const int sHeadMoods[%d][68] =' % MOODS)
out.append('{')
width = 0
for m in range(MOODS):
    row = []
    for i in range(50):
        mouth = word(0x4c5270 + m * 400 + i * 8)
        if mouth == -1:
            break
        row += [mouth, word(0x4c5274 + m * 400 + i * 8)]
    row.append(-1)
    width = max(width, len(row))
    out.append('\t{ %s },   // %d' % (', '.join(str(v) for v in row), m))
out.append('};')
assert width <= 68, width
out.append('')
out.append('// 0x4c4e10: the seven places of the board where a resting pointer shows a tip: left, top, right and bottom')
out.append('static const int sTipRegions[7][4] =')
out.append('{')
for r in range(7):
    out.append('\t{ %s },' % ', '.join(str(word(0x4c4e10 + r * 16 + i * 4)) for i in range(4)))
out.append('};')
out.append('')
out.append('// 0x4c4e80: where the tip\'s picture goes, and 0x4c4eb8 which picture it is (0 the bubble turned left to right, 1')
out.append("// the bubble, 2 the bubble turned top to bottom, 3 the bubble without its tail and a line closing it)")
out.append('static const int sTipPlaces[7][2] =')
out.append('{')
for r in range(7):
    out.append('\t{ %d, %d },' % (word(0x4c4e80 + r * 8), word(0x4c4e84 + r * 8)))
out.append('};')
out.append('static const int sTipFrames[7] = { %s };' % ', '.join(str(word(0x4c4eb8 + r * 4)) for r in range(7)))
out.append('')
out.append('// 0x4e57b0 (arcade and classic) and 0x4e5890 (strategy): the eight lines of each tip, as the addresses of the texts')
out.append('static const unsigned int sTipLines[2][7][8] =')
out.append('{')
for t, base in enumerate((0x4e57b0, 0x4e5890)):
    out.append('\t{')
    for r in range(7):
        out.append('\t\t{ %s },' % ', '.join('0x%08x' % (word(base + r * 32 + i * 4) & 0xffffffff) for i in range(8)))
    out.append('\t},')
out.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'HeadData.inc'), 'w', newline='\n').write(
    '\n'.join(out) + '\n')
print('HeadData.inc written, longest mood row %d numbers' % width)
