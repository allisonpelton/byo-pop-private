#!/usr/bin/env python3
"""Write src/Res.h and src/Res.cpp: the id enums and name tables of the game's resources, read from the pointer
table at 0x4e6a80 of the game image (re/rocketmania/bin/RocketManiaGame.exe; see docs/FRAMEWORK_2003.md):
entries 0..113 are images, 114..178 sounds, 179..182 music.

    python games/rocketmania/tools/gen_res.py
"""
import os, re, struct, sys
sys.path.insert(0, os.path.dirname(__file__))
import ptrtable

IMAGES, SOUNDS, MUSIC = 114, 65, 4
BS = chr(92)
names = []
for i in range(IMAGES + SOUNDS + MUSIC):
    p = struct.unpack_from('<I', ptrtable.d, ptrtable.off(0x4e6a80 + 4 * i))[0]
    names.append(ptrtable.cstr(p))


def ident(prefix, n):
    s = re.sub(r'[^A-Za-z0-9]+', '_', n.replace('voice' + BS, 'voice_').replace('music' + BS, '')).strip('_').upper()
    return prefix + s


def enum(prefix, items):
    ids = []
    seen = {}
    for n in items:
        k = ident(prefix, n)
        if k in seen:
            seen[k] += 1
            k = '%s_%d' % (k, seen[k])
        else:
            seen[k] = 0
        ids.append(k)
    return ids


img = enum('IMAGE_', names[:IMAGES])
snd = enum('SOUND_', names[IMAGES:IMAGES + SOUNDS])
mus = enum('MUSIC_', names[IMAGES + SOUNDS:])
out = os.path.join(os.path.dirname(__file__), '..', 'src')
with open(os.path.join(out, 'Res.h'), 'w', newline='\n') as f:
    f.write('// The resource ids of the game: the original keeps the names in one table of 183 file names (0x4e6a80,\n'
            '// docs/FRAMEWORK_2003.md): images 0..113, sounds 114..178 (ids 0..64 here), music 179..182. Generated by\n'
            '// tools/gen_res.py.\n#ifndef __RES_H__\n#define __RES_H__\n\nnamespace Sexy\n{\n\n')
    f.write('enum ImageId\n{\n' + ''.join('\t%s,\n' % k for k in img) + '\tNUM_IMAGES\n};\n\n')
    f.write('enum SoundId\n{\n' + ''.join('\t%s,\n' % k for k in snd) + '\tNUM_SOUNDS\n};\n\n')
    f.write('enum MusicId\n{\n' + ''.join('\t%s,\n' % k for k in mus) + '\tNUM_MUSIC\n};\n\n')
    f.write('extern const char* gImageNames[NUM_IMAGES];\nextern const char* gSoundNames[NUM_SOUNDS];\n'
            'extern const char* gMusicNames[NUM_MUSIC];\n\n}\n\n#endif\n')
with open(os.path.join(out, 'Res.cpp'), 'w', newline='\n') as f:
    f.write('// The name tables of Res.h (RocketManiaGame 0x4e6a80).\n#include "Res.h"\n\nnamespace Sexy\n{\n\n')

    def tab(nm, cnt, items):
        f.write('const char* %s[%s] =\n{\n' % (nm, cnt))
        for n in items:
            f.write('\t"%s",\n' % n.replace(BS, BS + BS))
        f.write('};\n\n')
    tab('gImageNames', 'NUM_IMAGES', names[:IMAGES])
    tab('gSoundNames', 'NUM_SOUNDS', names[IMAGES:IMAGES + SOUNDS])
    tab('gMusicNames', 'NUM_MUSIC', names[IMAGES + SOUNDS:])
    f.write('}\n')
print(len(img), len(snd), len(mus))
