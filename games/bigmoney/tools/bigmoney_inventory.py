#!/usr/bin/env python3
"""Write games/bigmoney/docs/INVENTORY.md: Big Money's game classes, their vtables and every game function.

Inputs are the Ghidra export (re/bigmoney/ghidra/functions.jsonl), the RTTI scan
(re/bigmoney/rtti.classes.json, tools/rtti_msvc70.py) and the SAF 1.2 headers for slot names. The
game code is 0x401000-0x421830; source files are in link (alphabetical) order, so each module is an
address range.

    python games/bigmoney/tools/bigmoney_inventory.py [--saf E:/retools/refs/saf12] [--out games/bigmoney/docs/INVENTORY.md]
"""
import argparse
import collections
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from saf_vtable_layout import Layout  # noqa: E402
NONVIRTUAL = ["SexyAppBase::ProcessDeferredMessages", "SexyAppBase::CursorThreadProc"]
GAME_LO, GAME_HI = 0x401000, 0x421830
# (module, first address); a module runs to the next one's start
MODULES = [
    ("Board.cpp (with Piece)", 0x401000), ("CreditsDialog.cpp", 0x40ee10), ("GameSelector.cpp", 0x40fb90),
    ("HelpWidget.cpp", 0x410d80), ("HighScoreDialog.cpp", 0x412280), ("HighScoreWidget.cpp", 0x412bf0),
    ("LockableButton.cpp", 0x414d80), ("MoneyDialog.cpp", 0x414e00), ("MrMoney.cpp", 0x415140),
    ("OptionsDialog.cpp", 0x415560), ("OverlayWidget.cpp", 0x417400), ("Points.cpp", 0x4174f0),
    ("RecordScoreDialog.cpp", 0x417730), ("RegisterDialog.cpp", 0x417e80), ("StartButton.cpp", 0x419260),
    ("TitleScreen.cpp", 0x419630), ("WinBMApp.cpp", 0x41b670), ("(end)", GAME_HI),
]
GAME_CLASSES = ["Piece", "Board", "CreditsDialog", "GameSelector", "HelpWidget", "HighScoreDialog",
                "HighScoreWidget", "LockableButton", "MoneyDialog", "MrMoney", "OptionsDialog", "OverlayWidget",
                "Points", "RecordScoreDialog", "RegisterDialog", "StartButton", "TitleScreen", "WinBMApp",
                "InternetManager", "BetaSupport"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--saf", default="E:/retools/refs/saf12")
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "bigmoney", "docs", "INVENTORY.md"))
    ap.add_argument("--functions", default=os.path.join(ROOT, "re", "bigmoney", "ghidra", "functions.jsonl"))
    ap.add_argument("--classes", default=os.path.join(ROOT, "re", "bigmoney", "rtti.classes.json"))
    args = ap.parse_args()

    funcs = {}
    for line in open(args.functions):
        f = json.loads(line)
        try:
            funcs[int(f["addr"], 16)] = f
        except ValueError:
            pass
    classes = json.load(open(args.classes))
    lay = Layout(args.saf, NONVIRTUAL)

    out = []
    w = out.append
    w("# Big Money Deluxe: game class and function inventory")
    w("")
    w("Generated by `games/bigmoney/tools/bigmoney_inventory.py` from the Ghidra export of the carved game PE and the RTTI")
    w("scan; names are the ones applied in Ghidra (`games/bigmoney/docs/symbols/*.jsonl`). Game code is")
    w("0x%x-0x%x. Slot names are SexyAppFramework 1.2's (`games/bigmoney/docs/FRAMEWORK_12.md`)." % (GAME_LO, GAME_HI))
    w("")
    w("## Classes")
    w("")
    w("| Class | Bases | Vtables (offset: slots) | Overridden slots |")
    w("|---|---|---|---|")
    vt_owner = {}
    for c in GAME_CLASSES:
        info = classes.get("Sexy::" + c)
        if not info:
            continue
        vts = ", ".join("+0x%x: %d" % (v["offset"], len(v["slots"])) for v in sorted(info["vtables"], key=lambda v: v["offset"]))
        prim = next((v for v in info["vtables"] if v["offset"] == 0), None)
        base = next((b.split("::")[-1] for b in info["bases"] if b.split("::")[-1] in lay.cls), None)
        base_table = lay.slots(base) if base else []
        own = []
        if prim:
            for i, a in enumerate(prim["slots"]):
                ai = int(a, 16)
                vt_owner.setdefault(ai, []).append("%s slot %d" % (c, i))
                if GAME_LO <= ai < GAME_HI:
                    nm = base_table[i][1] if i < len(base_table) else "(new virtual %d)" % i
                    own.append("%d `%s`" % (i, nm.split("(")[0] if i < len(base_table) else nm))
        for v in info["vtables"]:
            if v["offset"]:
                for i, a in enumerate(v["slots"]):
                    vt_owner.setdefault(int(a, 16), []).append("%s +0x%x slot %d" % (c, v["offset"], i))
        w("| %s | %s | %s | %s |" % (c, ", ".join(b.split("::")[-1] for b in info["bases"]), vts, "; ".join(own)))
    w("")
    w("## Functions by module")
    w("")
    total = collections.Counter()
    for (mod, lo), (_, hi) in zip(MODULES, MODULES[1:]):
        fs = sorted(a for a in funcs if lo <= a < hi)
        size = sum(funcs[a]["size"] for a in fs)
        w("### %s (0x%x-0x%x, %d functions, %d bytes)" % (mod, lo, hi, len(fs), size))
        w("")
        w("| Address | Bytes | Name | Vtable slots | Callers |")
        w("|---|---|---|---|---|")
        for a in fs:
            f = funcs[a]
            name = f["full"] if f["ns"] != "Global" else f["name"]
            w("| %08x | %d | %s | %s | %d |" % (a, f["size"], name.replace("|", "\\|"), "; ".join(vt_owner.get(a, [])),
                                                len(f["callers"])))
            total["fns"] += 1
            total["bytes"] += f["size"]
        w("")
    w("Total: %d functions, %d bytes." % (total["fns"], total["bytes"]))
    w("")
    open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote %s (%d functions)" % (args.out, total["fns"]))


if __name__ == "__main__":
    main()
