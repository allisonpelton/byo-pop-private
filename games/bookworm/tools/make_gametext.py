#!/usr/bin/env python3
"""Generate games/bookworm/src/GameTextTable.inc: where each of BookWorm's hard-coded texts is in the exe.

The port carries no game text (games/bookworm/src/GameText.h): it reads every text from the player's own
Bookworm.exe by address. This finds those addresses. The input is a working list of the texts (git-ignored,
it holds game text), one per line: an id, a tab, and the text written as a C string literal's contents
(\\n, \\r, \\t, \\", \\\\ and \\xNN escapes). The output holds only ids, addresses, lengths and hashes.

    python games/bookworm/tools/make_gametext.py re/bookworm/gametext.tsv [--exe re/bookworm/bin/BookwormGame.exe]
        [--out games/bookworm/src/GameTextTable.inc]

The exe can be the carved game image or the retail Bookworm.exe (the game PE after "!popcapcdprotect!").
Each text is looked up as a NUL-terminated string that starts after a NUL (string literals are padded), in
the order .rdata, .data, then anywhere; the first match wins.
"""
import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
MARKER = b"!popcapcdprotect!"


def unescape(s):
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c != "\\":
            out += c.encode("latin-1")
            i += 1
            continue
        n = s[i + 1]
        if n == "x":
            j = i + 2
            while j < len(s) and s[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(int(s[i + 2:j], 16) & 0xFF)
            i = j
            continue
        out += {"n": b"\n", "r": b"\r", "t": b"\t", '"': b'"', "\\": b"\\", "'": b"'", "0": b"\0"}[n]
        i += 2
    return bytes(out)


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def load_image(path):
    d = open(path, "rb").read()
    m = d.find(MARKER)
    base = d.find(b"MZ", m) if m >= 0 else 0
    pe = base + struct.unpack_from("<I", d, base + 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    imagebase = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    secs = []
    off = pe + 24 + optsz
    for _ in range(nsec):
        name = d[off:off + 8].rstrip(b"\0").decode("latin-1")
        va, rsz, rp = struct.unpack_from("<III", d, off + 12)
        secs.append((name, imagebase + va, base + rp, rsz))
        off += 40
    return d, secs


def find_va(d, secs, text):
    needle = text + b"\0"
    order = sorted(secs, key=lambda s: {".rdata": 0, ".data": 1}.get(s[0], 2))
    for name, va, rp, rsz in order:
        blob = d[rp:rp + rsz]
        pos = blob.find(needle)
        while pos >= 0:
            if pos == 0 or blob[pos - 1] == 0:
                return va + pos
            pos = blob.find(needle, pos + 1)
    for name, va, rp, rsz in order:
        pos = d[rp:rp + rsz].find(needle)
        if pos >= 0:
            return va + pos
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("texts")
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "bookworm", "bin", "BookwormGame.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "bookworm", "src", "GameTextTable.inc"))
    args = ap.parse_args()
    d, secs = load_image(args.exe)
    rows, seen, missing = [], set(), []
    for ln, line in enumerate(open(args.texts, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        gid, lit = line.split("\t", 1)
        if not gid.startswith("GT_") or gid in seen:
            sys.exit("line %d: bad or duplicate id %r" % (ln, gid))
        seen.add(gid)
        text = unescape(lit)
        va = find_va(d, secs, text)
        if va is None:
            missing.append(gid)
            continue
        rows.append((gid, va, len(text), fnv1a(text)))
    if missing:
        sys.exit("not found in the exe: " + ", ".join(missing))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by games/bookworm/tools/make_gametext.py. BookWorm Deluxe 1.03's hard-coded texts: id,\n")
        f.write("// address in the game image, length and FNV-1a hash. The texts themselves are read from the\n")
        f.write("// player's own Bookworm.exe at start-up (GameText.h); none are in the repository.\n")
        for gid, va, n, h in rows:
            f.write("GAMETEXT(%s, 0x%08x, %d, 0x%08x)\n" % (gid, va, n, h))
    print("wrote %s (%d texts)" % (args.out, len(rows)))


if __name__ == "__main__":
    main()
