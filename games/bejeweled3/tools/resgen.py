#!/usr/bin/env python3
"""port: writes games/bejeweled3/src/Res.h and Res.cpp, Bejeweled 3's resource globals as the exe's ResourceGen3
output has them (0x6e8ca0-0x70e2ff): an enum of every resource id, a global for each, the table that gives each global
to the resource manager (RegisterResourceGlobals: the manager sets a global whenever its resource loads), each image's
x/y offset, the id's name and back, and the extraction functions the game calls (ExtractInitResources and the like),
which take each resource of a group at the app's art size and fail when one is missing.

The ids and their order come from the exe (GetStringIdById's jump table, 0x6eca80); each resource's type from
properties/resources.xml; the order of the calls in each extraction function from the Ghidra export (re/bejeweled3/gh2),
where each is a line such as `DAT_008d75f8 = FUN_006efa20(0x2f9,600,0);`. The ids are identifiers, not text.

    python games/bejeweled3/tools/resgen.py [--exe assets/bejeweled3/bejeweled3.exe] [--xml ...] [--export ...]
"""
import argparse
import collections
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
NAME_TABLE = 0x6eca80  # GetStringIdById's jump table: each case is "mov eax, offset name; ret"
ID_MAX = 0xa4c
KINDS = {'Image': 'Image*', 'Font': 'Font*', 'Sound': 'int', 'PopAnim': 'PopAnim*', 'PIEffect': 'PIEffect*',
         'RenderEffect': 'RenderEffectDefinition*'}
# the exe's typed getters, each a GetXThrow of the manager that also records the resource's id
GETTERS = {0x6efa20: 'Image', 0x6ef860: 'Sound', 0x6ef940: 'Font', 0x6ef780: 'PopAnim', 0x6ef6a0: 'PIEffect',
           0x6ef5c0: 'RenderEffect'}
# each extraction function the game calls: its group, then the art sizes' parts and the part every size shares
EXTRACTS = [
    ('Init', 0x70e260, [(600, 0x704a40), (768, 0x6fb660), (1200, 0x70df20)], 0x6f21a0),
    ('Loader', 0x70e1b0, [(600, 0x7048b0), (768, 0x6fb4d0), (1200, 0x70dd90)], None),
    ('LoadingThread', 0x70e0f0, [(600, 0x6fb830), (768, 0x6f2450), (1200, 0x704d30)], 0x6efc50),
    ('2DOnly', None, [], 0x704c10),
]
HEADER = ['// Generated by games/bejeweled3/tools/resgen.py from the exe\'s resource id table, properties/resources.xml and',
          '// the export\'s extraction functions: the resource globals and their ids, as the exe\'s ResourceGen3 output has',
          '// them (0x6e8ca0-0x70e2ff (bejeweled3)). The ids are the names of the resources in that file.']


def va_to_off(d, va):
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from('<IIII', d, s + i * 40 + 8)
        if rva <= va - base < rva + min(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def exe_ids(path):
    d = open(path, 'rb').read()
    ids = []
    for i in range(ID_MAX):
        case = va_to_off(d, struct.unpack_from('<I', d, va_to_off(d, NAME_TABLE + 4 * i))[0])
        if d[case] != 0xB8:
            sys.exit('id %d: unexpected code at the name table' % i)
        o = va_to_off(d, struct.unpack_from('<I', d, case + 1)[0])
        ids.append(d[o:d.index(b'\0', o)].decode('ascii'))
    return ids


def xml_kinds(path):
    text = open(path, encoding='utf-8-sig', errors='replace').read()
    kind = {}
    for m in re.finditer(r'<(Image|Font|Sound|PopAnim|PIEffect|RenderEffect)\s+id="([^"]+)"', text):
        if kind.setdefault(m.group(2), m.group(1)) != m.group(1):
            sys.exit('%s is both %s and %s' % (m.group(2), kind[m.group(2)], m.group(1)))
    return kind


def export_calls(export, address, ids):
    """the (kind, id name, art size) of each getter call of the function at address, in order"""
    m = re.search(r'// %08x  Global::FUN_%08x\n(.*?)\n// [0-9a-f]{8}  ' % (address, address), export, re.S)
    if m is None:
        sys.exit('no function at 0x%x in the export' % address)
    calls = []
    for f, args in re.findall(r'= FUN_00(6ef[0-9a-f]{3})\(([^)]*)\)', m.group(1)):
        kind = GETTERS.get(int(f, 16))
        if kind is None:
            sys.exit('0x%x calls 0x%s, which is not a getter' % (address, f))
        parts = [a.strip() for a in args.split(',')]
        calls.append((kind, ids[int(parts[0], 0)], int(parts[1], 0) if len(parts) > 1 else 0))
    return calls


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--exe', default=os.path.join(ROOT, 'assets', 'bejeweled3', 'bejeweled3.exe'))
    ap.add_argument('--xml', default=os.path.join(ROOT, 'assets', 'bejeweled3', 'properties', 'resources.xml'))
    ap.add_argument('--export', default=os.path.join(ROOT, 're', 'bejeweled3', 'gh2', 'all.c'))
    args = ap.parse_args()
    ids = exe_ids(args.exe)
    kind = xml_kinds(args.xml)
    missing = [r for r in ids if r not in kind] + [r for r in kind if r not in set(ids)]
    if missing:
        sys.exit('ids in only one of the exe and the xml: %s' % ' '.join(missing))
    export = open(args.export, encoding='utf-8', errors='replace').read()

    by_kind = collections.Counter(kind[r] for r in ids)
    h = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class PopAnim;', 'class PIEffect;',
                  'class RenderEffectDefinition;', 'class PrimeResourceManager;', '', 'enum ResourceId {']
    h += ['\t%s_ID,' % rid for rid in ids]
    h += ['\tRESOURCE_ID_MAX', '};', '',
          '// 0x6efb20 (bejeweled3): gives each global to the manager, which sets it whenever its resource loads, and takes',
          '// each image\'s offset. The manifest must be parsed and the art size set.',
          'void RegisterResourceGlobals(PrimeResourceManager* theManager);',
          'void* GetResourceById(int theId);           // 0x6ef3f0 (bejeweled3): the id\'s global, null for -1',
          'int GetImageOffsetX(int theId);             // 0x6ef3c0 (bejeweled3): the image\'s x= in resources.xml',
          'int GetImageOffsetY(int theId);             // 0x6ef3b0 (bejeweled3)',
          'const char* GetStringIdById(int theId);     // 0x6e8ca0 (bejeweled3)',
          'int GetIdByStringId(const char* theName);   // 0x6ef410 (bejeweled3): -1 for none',
          '']
    for g, address, parts, common in EXTRACTS:
        a = address if address is not None else common
        h.append('bool Extract%sResources(PrimeResourceManager* theManager);  // 0x%x (bejeweled3)' % (g, a))
    h.append('')
    for k in ['Font', 'Image', 'Sound', 'PopAnim', 'PIEffect', 'RenderEffect']:
        h.append('// %s (%d)' % (k, by_kind[k]))
        h += ['extern %s %s;' % (KINDS[k], rid) for rid in ids if kind[rid] == k]
        h.append('')
    h.append('}  // namespace Sexy')

    c = HEADER + ['#include "Res.h"', '', '#include "AutoCrit.h"', '#include "CritSect.h"', '#include "PrimeResourceManager.h"', '',
                  '#include <cstring>', '#include <map>', '#include <string>', '', 'using namespace Sexy;', '']
    for rid in ids:
        c.append('%s Sexy::%s = %s;' % (KINDS[kind[rid]], rid, '0' if KINDS[kind[rid]] == 'int' else 'nullptr'))
    c += ['', 'namespace {', '',
          '// 0x8cf5c8 (bejeweled3): the address of each id\'s global',
          'void* const gResources[RESOURCE_ID_MAX] = {']
    c += ['\t&%s,' % rid for rid in ids]
    c += ['};', '',
          'const char* const gResourceNames[RESOURCE_ID_MAX] = {']
    c += ['\t"%s",' % rid for rid in ids]
    c += ['};', '',
          '// 0x8d9678 (bejeweled3): each image\'s offset (the original keeps a pointer to the resource\'s, which does not',
          '// change after the manifest is read)',
          'Point gImageOffsets[RESOURCE_ID_MAX];', '',
          '// 0x8e1f98 (bejeweled3): the lock of the map from each resource got through a getter to its id, which the loading',
          '// thread fills',
          'CritSect& ResourceIdLock() { static CritSect aLock; return aLock; }',
          'std::map<const void*, int>& ResourceIdMap() { static std::map<const void*, int> aMap; return aMap; }', '',
          'void RecordResourceId(const void* theResource, int theId)',
          '{',
          '\tAutoCrit aLock(ResourceIdLock());',
          '\tResourceIdMap()[theResource] = theId;',
          '}', '',
          'Image* GetImageThrow(PrimeResourceManager* theManager, int theId, int theArtRes)  // 0x6efa20 (bejeweled3)',
          '{',
          '\tImage* anImage = theManager->GetImageThrow(gResourceNames[theId], theArtRes, false);',
          '\tRecordResourceId(anImage, theId);',
          '\treturn anImage;',
          '}', '',
          'int GetSoundThrow(PrimeResourceManager* theManager, int theId)  // 0x6ef860 (bejeweled3)',
          '{',
          '\treturn theManager->GetSoundThrow(gResourceNames[theId]);',
          '}', '',
          'Font* GetFontThrow(PrimeResourceManager* theManager, int theId, int theArtRes)  // 0x6ef940 (bejeweled3)',
          '{',
          '\tFont* aFont = theManager->GetFontThrow(gResourceNames[theId], theArtRes);',
          '\tRecordResourceId(aFont, theId);',
          '\treturn aFont;',
          '}', '',
          'PopAnim* GetPopAnimThrow(PrimeResourceManager* theManager, int theId)  // 0x6ef780 (bejeweled3)',
          '{',
          '\tPopAnim* aPopAnim = theManager->GetPopAnimThrow(gResourceNames[theId]);',
          '\tRecordResourceId(aPopAnim, theId);',
          '\treturn aPopAnim;',
          '}', '',
          'PIEffect* GetPIEffectThrow(PrimeResourceManager* theManager, int theId)  // 0x6ef6a0 (bejeweled3)',
          '{',
          '\tPIEffect* anEffect = theManager->GetPIEffectThrow(gResourceNames[theId]);',
          '\tRecordResourceId(anEffect, theId);',
          '\treturn anEffect;',
          '}', '',
          'RenderEffectDefinition* GetRenderEffectThrow(PrimeResourceManager* theManager, int theId)  // 0x6ef5c0 (bejeweled3)',
          '{',
          '\tRenderEffectDefinition* anEffect = theManager->GetRenderEffectThrow(gResourceNames[theId]);',
          '\tRecordResourceId(anEffect, theId);',
          '\treturn anEffect;',
          '}', '']

    def part(name, address):
        calls = export_calls(export, address, ids)
        body = ['bool %s(PrimeResourceManager* theManager)  // 0x%x (bejeweled3)' % (name, address), '{',
                '\tRegisterResourceGlobals(theManager);', '\ttry {']
        for k, rid, art in calls:
            if kind[rid] != k:
                sys.exit('0x%x gets %s as %s, which the manifest has as %s' % (address, rid, k, kind[rid]))
            if k in ('Image', 'Font'):
                body.append('\t\t%s = Get%sThrow(theManager, %s_ID, %d);' % (rid, k, rid, art))
            else:
                body.append('\t\t%s = Get%sThrow(theManager, %s_ID);' % (rid, k, rid))
        body += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
        return body, len(calls)

    count = 0
    public = []  # a group with no parts by art size is the game's function itself, outside the namespace
    for g, address, parts, common in EXTRACTS:
        for art, a in parts:
            body, n = part('Extract%s%dResources' % (g, art), a)
            c += body
            count += n
        if common is not None:
            if address is not None:
                body, n = part('Extract%sCommonResources' % g, common)
                c += body
            else:
                body, n = part('Sexy::Extract%sResources' % g, common)
                public += body
            count += n
    c += ['}  // namespace', ''] + public

    c += ['void Sexy::RegisterResourceGlobals(PrimeResourceManager* theManager)',
          '{',
          '\tfor (int anId = 0; anId < RESOURCE_ID_MAX; anId++) {',
          '\t\ttheManager->RegisterGlobalPtr(gResourceNames[anId], (void**)gResources[anId]);',
          '\t\tgImageOffsets[anId] = theManager->GetImageOffset(gResourceNames[anId]);',
          '\t}',
          '}', '',
          'void* Sexy::GetResourceById(int theId) { return theId == -1 ? nullptr : *(void**)gResources[theId]; }',
          'int Sexy::GetImageOffsetX(int theId) { return gImageOffsets[theId].mX; }',
          'int Sexy::GetImageOffsetY(int theId) { return gImageOffsets[theId].mY; }',
          'const char* Sexy::GetStringIdById(int theId) { return (unsigned)theId < RESOURCE_ID_MAX ? gResourceNames[theId] : ""; }',
          '',
          '// The original fills a map from the names once (the later of two equal names wins) and looks the name up in it',
          'int Sexy::GetIdByStringId(const char* theName)',
          '{',
          '\tstatic std::map<std::string, int> aMap;',
          '\tif (aMap.empty()) {',
          '\t\tfor (int anId = 0; anId < RESOURCE_ID_MAX; anId++)',
          '\t\t\taMap[gResourceNames[anId]] = anId;',
          '\t}',
          '\tstd::map<std::string, int>::iterator anItr = aMap.find(theName);',
          '\treturn anItr == aMap.end() ? -1 : anItr->second;',
          '}', '']
    for g, address, parts, common in EXTRACTS:
        if address is None:
            continue
        c += ['bool Sexy::Extract%sResources(PrimeResourceManager* theManager)  // 0x%x (bejeweled3)' % (g, address), '{',
              '\tRegisterResourceGlobals(theManager);']
        for art, a in parts:
            c.append('\tif (theManager->mCurArtRes == %d && !Extract%s%dResources(theManager))' % (art, g, art))
            c.append('\t\treturn false;')
        if common is not None:
            c.append('\tif (!Extract%sCommonResources(theManager))' % g)
            c.append('\t\treturn false;')
        c += ['\treturn true;', '}', '']

    os.makedirs(SRC, exist_ok=True)
    open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='').write('\n'.join(h) + '\n')
    open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    print('%d ids, %d calls in %d extraction functions -> Res.h, Res.cpp' % (len(ids), count, len(EXTRACTS)))


if __name__ == '__main__':
    main()
