#!/usr/bin/env python3
"""Generate games/mummymaze/src/Res.h and Res.cpp: the ids and file names of the images and sounds.

WinMM.exe has no resource manager: two tables of file names (pointers to C strings in .data), indexed by the ids the
game code uses (mImages[id], PlaySample(id)). This reads them from the user's exe, so the ids keep the original's
order. Only file names are written (no game text).

    python games/mummymaze/tools/make_res.py [--exe re/mummymaze/bin/WinMM.exe] [--out games/mummymaze/src]
"""
import argparse
import os
import struct

IMAGE_TABLE = 0x492410    # 165 pointers, up to the sounds' table
SOUND_TABLE = 0x4926a4    # 25 pointers
SOUND_END = 0x492708
# the two pictures of the registration screen and the title's "registered version" medallion: the port has no registration
# (CLAUDE.md, "Order of the work"), so they are neither named nor loaded, and the ids after them move up. So do the two
# pictures that only the Internet score list drew (internethighscore, dbuttonclear: 0x416540, 0x415e50, code the port has not
# got). light6, light8 and light10, which no code names, stay: they are the explorer's fourth idle animation, reached as
# readmap6 + size + 3 * kind.
OMITTED_IMAGES = ("register", "registerrunes", "trialcircle", "internethighscore", "dbuttonclear")


class Exe:
    def __init__(self, path):
        d = self.d = open(path, "rb").read()
        pe = struct.unpack_from("<I", d, 0x3C)[0]
        nsec = struct.unpack_from("<H", d, pe + 6)[0]
        opt = struct.unpack_from("<H", d, pe + 20)[0]
        self.base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
        off = pe + 24 + opt
        self.secs = []
        for _ in range(nsec):
            vsz, va, rsz, rp = struct.unpack_from("<IIII", d, off + 8)
            self.secs.append((self.base + va, rsz, rp))
            off += 40

    def off(self, va):
        for sva, rsz, rp in self.secs:
            if sva <= va < sva + rsz:
                return rp + va - sva
        raise ValueError(hex(va))

    def u32(self, va):
        return struct.unpack_from("<I", self.d, self.off(va))[0]

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)].decode("latin1")


def ids(prefix, names):
    seen = {}
    out = []
    for n in names:
        base = prefix + n.upper()
        k = seen.get(base, 0)
        seen[base] = k + 1
        out.append(base if k == 0 else "%s_%d" % (base, k + 1))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", "..", ".."))
    ap.add_argument("--exe", default=os.path.join(root, "re", "mummymaze", "bin", "WinMM.exe"))
    ap.add_argument("--out", default=os.path.join(here, "..", "src"))
    args = ap.parse_args()
    e = Exe(args.exe)
    images = [e.cstr(e.u32(IMAGE_TABLE + 4 * i)) for i in range((SOUND_TABLE - IMAGE_TABLE) // 4)]
    sounds = [e.cstr(e.u32(SOUND_TABLE + 4 * i)) for i in range((SOUND_END - SOUND_TABLE) // 4)]
    exe_images = len(images)
    images = [n for n in images if n not in OMITTED_IMAGES]
    iids = ids("IMAGE_", images)
    sids = ids("SOUND_", sounds)

    h = ["#ifndef __MUMMYMAZE_RES_H__", "#define __MUMMYMAZE_RES_H__", "",
         "// Mummy Maze Deluxe's shared ids: images and sounds (WinMM.exe has no ResourceManager use: two hard-coded",
         "// file-name tables, indexed by these ids). Generated by games/mummymaze/tools/make_res.py from the exe:",
         "//   gImageNames 0x492410 (%d, %d here), loaded by MummyApp::LoadImage (0x41db90) as GetImage(\"images\\\\\" + name)" % (exe_images, len(images)),
         "//   gSoundNames 0x4926a4 (%d), loaded by the loading thread (0x41dd60) as LoadSound(id, \"sounds\\\\\" + name)" % len(sounds),
         "// Every id is used as mApp->mImages[IMAGE_X] and PlaySample(SOUND_X). The 6, 8 and 10 variants are the three",
         "// maze sizes' tiles (the id of the 6 variant plus 0, 1 or 2).", "", "namespace Sexy", "{", "", "enum ImageId", "{"]
    for i, n in enumerate(iids):
        h.append("\t%s = %d," % (n, i))
    h += ["\tNUM_IMAGES = %d" % len(images), "};", "", "enum SoundId", "{"]
    for i, n in enumerate(sids):
        h.append("\t%s = %d," % (n, i))
    h += ["\tNUM_SOUNDS = %d" % len(sounds), "};", "",
          "extern const char* gImageNames[NUM_IMAGES];", "extern const char* gSoundNames[NUM_SOUNDS];", "", "}", "",
          "#endif", ""]
    open(os.path.join(args.out, "Res.h"), "w", newline="\n").write("\n".join(h))
    c = ["// The name tables of Res.h (WinMM.exe 0x492410 and 0x4926a4). Generated by games/mummymaze/tools/make_res.py.",
         '#include "Res.h"', "", "namespace Sexy", "{", "", "const char* gImageNames[NUM_IMAGES] =", "{"]
    c += ['\t"%s",' % n for n in images]
    c += ["};", "", "const char* gSoundNames[NUM_SOUNDS] =", "{"]
    c += ['\t"%s",' % n for n in sounds]
    c += ["};", "", "}", ""]
    open(os.path.join(args.out, "Res.cpp"), "w", newline="\n").write("\n".join(c))
    print("%d images, %d sounds" % (len(images), len(sounds)))


if __name__ == "__main__":
    main()
