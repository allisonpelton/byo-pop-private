#!/usr/bin/env python3
"""Generate games/mummymaze/src/GameTextTable.inc: where each of Mummy Maze's hard-coded texts is in the exe.

The port carries no game text (games/mummymaze/src/GameText.h): it reads every text from the player's own
WinMM.exe by address. This finds those addresses. The input is Ghidra's string export of the game image
(re/mummymaze/gh/strings.jsonl, git-ignored: it holds game text); the output holds only addresses, lengths and
hashes. Only the texts the port's code names are listed (GT(0xADDR), and the tables of addresses in its .cpp and .inc
files): the original's other strings (registration, the Internet scores, the framework's) are not the port's, so the
table does not point at them. A text the port starts to use is in the table after this script runs again.

    python games/mummymaze/tools/make_gametext.py [--strings re/mummymaze/gh/strings.jsonl] [--exe re/mummymaze/bin/WinMM.exe]
        [--out games/mummymaze/src/GameTextTable.inc]
"""
import argparse
import glob
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
FIRST = 0x480000   # the game's strings (.rdata and .data: dialog texts, tutorial pages, labels)
LAST = 0x4ae000
GAME_CODE_END = 0x42e000   # the game's own functions end here; the framework and the C library follow


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + max(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def named_in_port(src):
    """The addresses the port's code names: every 0x00XXXXXX literal of its sources (the level tables' addresses are data)."""
    used = set()
    for path in glob.glob(os.path.join(src, "**", "*"), recursive=True):
        if not path.endswith((".cpp", ".h", ".inc")) or os.path.basename(path) in ("GameTextTable.inc", "GameLevelsTable.inc"):
            continue
        for m in re.finditer(r"0x00([0-9a-fA-F]{6})(?![0-9a-fA-F])", open(path, encoding="utf-8", errors="replace").read()):
            used.add(int(m.group(1), 16))
    return used


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strings", default=os.path.join(ROOT, "re", "mummymaze", "gh", "strings.jsonl"))
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "mummymaze", "bin", "WinMM.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "mummymaze", "src", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    strs = {}
    for line in open(args.strings):
        j = json.loads(line)
        if j["type"] == "string":
            strs[int(j["addr"], 16)] = j["value"]
    # the strings that the game's own functions refer to (s_..._<addr> and DAT_<addr> in the decompilation)
    decomp = os.path.join(os.path.dirname(args.strings), "decomp")
    rows = []
    known = set()
    for path in glob.glob(os.path.join(decomp, "_global", "*.c")):
        if int(os.path.basename(path)[:8], 16) >= GAME_CODE_END:
            continue
        for m in re.finditer(r"s_\w+?_([0-9a-f]{8})|DAT_([0-9a-f]{8})", open(path, encoding="latin1").read()):
            va = int(m.group(1) or m.group(2), 16)
            if va in known or not (FIRST <= va < LAST):
                continue
            try:
                o = va_to_off(d, va)
            except ValueError:
                continue
            e = d.find(bytes(1), o)
            if e < 0:
                continue
            t = d[o:e]
            if (va in strs) or (1 <= len(t) < 200 and all(32 <= c < 127 or c in (9, 10, 13) for c in t)):
                rows.append(va)
                known.add(va)
    # every other printable string of the game's text region (the labels, file names and formats between the code's data and
    # the tutorial table), so that any of them can be named as GT(0xADDR)
    va = 0x48d1c0
    while va < 0x49bd60:
        o = va_to_off(d, va)
        e = d.find(bytes(1), o)
        t = d[o:e]
        if len(t) >= 2 and all(32 <= c < 127 or c in (9, 10, 13) for c in t) and va not in known:
            rows.append(va)
            known.add(va)
        va += (e - o) + 1
    used = named_in_port(os.path.dirname(args.out))
    found = len(rows)
    rows = sorted(va for va in rows if va in used)
    out = ["// Generated by games/mummymaze/tools/make_gametext.py. The hard-coded strings of Mummy Maze Deluxe 1.1 that the port names:",
           "// address in the game image, length and FNV-1a hash. The texts themselves are read from the",
           "// player's own WinMM.exe at start-up (GameText.h); none are in the repository."]
    for va in rows:
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries (of %d strings found) to %s" % (len(rows), found, args.out))


if __name__ == "__main__":
    sys.exit(main())
