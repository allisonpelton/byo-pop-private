#!/usr/bin/env python3
"""Phase one of the identical-play pass: the same input in the original and the port, compared by game state.

  identical.py script <port log> <script out> [--offset N]
      the origrun script that gives the original the port bot's input: the menu clicks and one `at <update> ...` per
      input line of the port's -autoplaylog (the port's updates plus OFFSET, the original's update when its classic
      board starts minus the port's)
  identical.py compare <port log> <offset> <origrun log>:<set> ...
      the changes of the values in the port's `T <update> <name> <value>` lines against the original's `--watch`
      lines of the same expressions (SETS below), each shifted by OFFSET; prints the first differences
"""
import re
import sys

# the original's own memory: the app is the static 0x49c198, its board pointer +0x103b4 (0x4ac54c)
B = '0x4ac54c'
SETS = {
    'A': [('board', B), ('state', '[%s]+0x5c' % B), ('ex', '[[%s]+0x60]+0x50' % B), ('ey', '[[%s]+0x60]+0x54' % B)],
    'B': [('m0x', '[[%s]+0x64]+0x50' % B), ('m0y', '[[%s]+0x64]+0x54' % B), ('m1x', '[[%s]+0x68]+0x50' % B),
          ('m1y', '[[%s]+0x68]+0x54' % B)],
    'C': [('sx', '[[%s]+0x6c]+0x50' % B), ('sy', '[[%s]+0x6c]+0x54' % B), ('death2', '[%s]+0x298' % B), ('score', '0x4ac59c')],
    'E': [('mode', '0x4ac570'), ('tbase', '[%s]+0x4b4' % B), ('ebase', '0x4ac640'), ('undo', '[%s]+0x2e4' % B)],
    'F': [('rng', '0x4aed00')],
    'H': [('hs', '0x4ac540'), ('hcount', '[0x4ac540]+0xc0'), ('hasked', '[0x4ac540]+0xc4'), ('hlink', '0x4ac544')],
    'G': [('panel', '0x4ac538'), ('pstate', '[0x4ac538]+0x58'), ('poff', '[0x4ac538]+0x50'), ('mstate', '[%s]+0x5c' % B)],
    'D': [('maze', '[%s]+0x2b0' % B), ('file', '[%s]+0x2b4' % B), ('chamber', '0x4ac5bc'), ('pyramid', '0x4ac5c0')],
}


def port_inputs(path):
    out = []
    for line in open(path):
        m = re.match(r'\s+key (\d+) at app update (\d+)', line)
        if m:
            out.append((int(m.group(2)), 'key %s' % m.group(1)))
        m = re.match(r'\s+(click|menuclick) (\d+) (\d+) at app update (\d+)', line)
        if m:
            out.append((int(m.group(4)), '%s %s %s' % (m.group(1), m.group(2), m.group(3))))
        m = re.match(r'\s+text (\S+) at app update (\d+)', line)
        if m:
            out.append((int(m.group(2)), 'text %s' % m.group(1)))
    return out


def settle(events):
    """One value per update, the last, and only where it differs from the one before: the port's trace is taken once per
    update, and the original's poll can see a value that a later step of the same update changed again"""
    out = []
    for u, v in events:
        if out and out[-1][0] == u:
            out.pop()
        if out and out[-1][1] == v:
            continue
        out.append((u, v))
    return out


def port_events(path):
    ev = {}
    cap = None
    for line in open(path):
        m = re.match(r'T (\d+) (\w+) (-|\d+)$', line.strip())
        if m:
            ev.setdefault(m.group(2), []).append((int(m.group(1)), m.group(3)))
        m = re.match(r'cap reached at update (\d+)', line)
        if m:
            cap = int(m.group(1))
    if cap is not None:	# the bot's Shutdown after the cap takes the board away: not play
        for n in ev:
            ev[n] = [(u, v) for u, v in ev[n] if u < cap]
    return {n: settle(v) for n, v in ev.items()}


def orig_events(path, names):
    ev = {}
    for line in open(path):
        m = re.search(r'watch (\d): (\S+) -> (\S+) at update (\d+)', line)
        if not m:
            continue
        name = names[int(m.group(1)) - 1]
        old, new, u = m.group(2), m.group(3), int(m.group(4))
        if old == '?':
            continue
        if name == 'board':
            new = '1' if new not in ('0', '-') else '0'
        ev.setdefault(name, []).append((u, new))
    return {n: settle(v) for n, v in ev.items()}


def cmd_script(argv):
    port, out = argv[0], argv[1]
    off = None
    if '--offset' in argv:
        off = int(argv[argv.index('--offset') + 1])
    inputs = port_inputs(port)
    # the title's play link at 1500 and the main menu's link at 2400 (the original's load takes about 1400 updates and the
    # scroll after the title's click about 800); the port's bot is at the menu at once, so its updates are moved by the
    # difference. The main menu's click is the first one, and it starts the game.
    menu = [i for i, (u, c) in enumerate(inputs) if c.startswith('menuclick')]
    lines = ['# generated by identical.py from %s' % port, 'at 1500 click 323 470']
    if menu:
        mu, mc = inputs[menu[0]]
        lines.append('at 2400 click %s' % mc.split(' ', 1)[1])
        if off is None:
            off = 2400 - mu
        inputs = inputs[menu[0] + 1:]
    if off is None:
        off = 2301
    last = 0
    for u, c in inputs:
        if c.startswith('menuclick'):
            c = 'click' + c[9:]
        if c.startswith('key '):	# the game polls its key state: down for the one update the bot holds it
            lines.append('at %d kdown %s' % (u + off, c[4:]))
            lines.append('at %d kup %s' % (u + off + 1, c[4:]))
        else:
            if c.startswith('click '):	# a button needs the pointer over it first: a move, then the click
                lines.append('at %d move %s' % (u + off - 1, c[6:]))
            lines.append('at %d %s' % (u + off, c))
        last = max(last, u + off)
    lines.append('at %d move 1 1' % (last + 300))
    head = [l for l in lines if not l.startswith('at ')]
    body = sorted((l for l in lines if l.startswith('at ')), key=lambda l: int(l.split()[1]))
    open(out, 'w').write('\n'.join(head + body + ['quit']) + '\n')


def cmd_compare(argv):
    port, off = argv[0], int(argv[1])
    pe = port_events(port)
    bad = 0
    last_port = max(u for v in pe.values() for u, _ in v) if pe else 0
    # an oddity: the end-of-game scene's board never sets its maze and file (uninitialized in the original, which shows
    # the board before's); the port holds 1 and 0. Those two values are not compared while the scene is up.
    scene = []
    modes = pe.get('mode', [])
    for i, (u, v) in enumerate(modes):
        if v in ('2', '3', '4', '5', '6', '7', '8'):
            scene.append((u, modes[i + 1][0] if i + 1 < len(modes) else 1 << 30))
    def in_scene(u):
        return any(a <= u - off < b for a, b in scene)
    for spec in argv[2:]:
        path, s = spec.rsplit(':', 1)
        names = [n for n, _ in SETS[s]]
        oe = orig_events(path, names)
        for n in names:
            a = [(u + off, v) for u, v in pe.get(n, [])]
            b = [(u, v) for u, v in oe.get(n, []) if u <= last_port + off]
            if n == 'rng':	# the generator's seeding happens before the first update: the games' draws start at the menu click
                a = [(u, v) for u, v in a if u > 2400]
                b = [(u, v) for u, v in b if u > 2400]
            if n in ('maze', 'file'):
                a = [(u, v) for u, v in a if not in_scene(u)]
                b = [(u, v) for u, v in b if not in_scene(u)]
                a = [(u, v) for u, v in a if v != '-']	# the board's going away: no value
                b = [(u, v) for u, v in b if v != '-']
                a, b = settle(a), settle(b)	# a value the scene left behind equals the next one: not a change
                a = [(u, v) for i, (u, v) in enumerate(a) if i == 0 or v != a[i - 1][1]]
                if not a and b and b[0][1] == '0':	# the port never changed from 0: the original's first real value is 0 too
                    b = b[1:]
            # the original's first reading of a value is "- -> x" or "0 -> x" at the board's start: the same lines
            n_ok = 0
            for i in range(max(len(a), len(b))):
                x = a[i] if i < len(a) else None
                y = b[i] if i < len(b) else None
                if x != y:
                    bad += 1
                    print('DIFF %s #%d: port %s, original %s' % (n, i, x, y))
                    break
                n_ok += 1
            else:
                print('same %s: %d changes' % (n, n_ok))
    print('RESULT: %s' % ('identical' if bad == 0 else '%d values differ' % bad))
    return bad


def cmd_watches(argv):
    for n, e in SETS[argv[0]]:
        print('--watch', e)


if __name__ == '__main__':
    cmd = sys.argv[1]
    if cmd == 'script':
        cmd_script(sys.argv[2:])
    elif cmd == 'compare':
        sys.exit(1 if cmd_compare(sys.argv[2:]) else 0)
    elif cmd == 'watches':
        cmd_watches(sys.argv[2:])
