#!/usr/bin/env python3
"""Generate games/mummymaze/src/TutorialMazes.inc: the walls of the tutorial's five hard-coded 6 x 6 mazes, read from
Ghidra's decompilation of WinMM.exe 0x40f520 (the statements `cell |= bits`). Numbers only.

    python games/mummymaze/tools/make_tutorial.py [--decomp re/mummymaze/gh/decomp/_global] [--out games/mummymaze/src/TutorialMazes.inc]
"""
import argparse
import glob
import os
import re

OR = re.compile(r"\*\(uint \*\)\(\(int\)this \+ (\w+)\) = \*\(uint \*\)\(\(int\)this \+ \1\) \| (\w+);")


def num(s):
    return int(s, 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", "..", ".."))
    ap.add_argument("--decomp", default=os.path.join(root, "re", "mummymaze", "gh", "decomp", "_global"))
    ap.add_argument("--out", default=os.path.join(here, "..", "src", "TutorialMazes.inc"))
    args = ap.parse_args()
    t = open(glob.glob(os.path.join(args.decomp, "0040f520_*.c"))[0], encoding="latin1").read()
    parts = {}
    cur = None
    for ln in t.split("\n"):
        m = re.match(r"\s*case (\d+):", ln)
        if m:
            cur = int(m.group(1))
            parts[cur] = []
            continue
        if cur is None:
            continue
        m = OR.search(ln)
        if m:
            off = num(m.group(1))
            parts[cur].append(((off - 0x300) // 4, num(m.group(2))))
    out = ["// Generated by games/mummymaze/tools/make_tutorial.py from the decompilation of WinMM.exe 0x40f520:",
           "// per tutorial part, the wall bits OR-ed into the cells (index = x * 10 + y). Numbers only.", ""]
    for p in sorted(parts):
        out.append("static const int kTutorialWalls%d[][2] =" % p)
        out.append("{")
        for i, v in parts[p]:
            out.append("\t{%d, %d}," % (i, v))
        out.append("};")
        out.append("")
    # the tutorial's texts: a table of 67 strings built at start-up by 0x403450, named by address (no text here)
    src = open(glob.glob(os.path.join(args.decomp, "00403450_*.c"))[0], encoding="latin1").read()
    texts = {}
    for m in re.finditer(r"&DAT_([0-9a-f]{8}),\s*(?:\(\w+ \*\))?s_\w+?_([0-9a-f]{8})", src):
        texts[(int(m.group(1), 16) - 0x49bd68) // 16] = int(m.group(2), 16)
    out.append("// the addresses of the tutorial's texts in the exe, by step (0x403450)")
    out.append("static const unsigned kTutorialText[%d] =" % (max(texts) + 1))
    out.append("{")
    for i in range(max(texts) + 1):
        out.append("\t0x%08x," % texts.get(i, 0))
    out.append("};")
    out.append("")
    open(args.out, "w", newline="\n").write("\n".join(out))
    print({p: len(v) for p, v in parts.items()}, len(texts), "texts")


if __name__ == "__main__":
    main()
