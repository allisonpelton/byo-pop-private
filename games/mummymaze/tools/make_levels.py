#!/usr/bin/env python3
"""Generate games/mummymaze/src/GameLevelsTable.inc: where the level data is in WinMM.exe 1.1 (address, count, hash).
No data: the game reads it from the player's own exe at start-up (src/GameLevels.h).

    python games/mummymaze/tools/make_levels.py [--exe re/mummymaze/bin/WinMM.exe] [--out games/mummymaze/src/GameLevelsTable.inc]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_res import Exe

# name, address, number of 32-bit ints
TABLES = [
    ("kAdventureMaze", 0x48f458, 225),         # per pyramid and chamber (15 x 15): the maze file number
    ("kAdventureLevel", 0x48f7dc, 225),        # per pyramid and chamber: the maze number in the file, minus 1
    ("kExcluded", 0x48fb60, 2 * 481),          # (file, maze) pairs a classic game never picks, after a leading word
    ("kExcludedResume", 0x492708, 2 * 483),    # (file, maze) pairs that LoadClassic (0x41c600) skips when it picks the next chamber of a saved game
    ("kMapPos", 0x481b44, 30),                 # the world map: where each of the 15 pyramids is (x, y pairs)
    ("kMapLinks", 0x481bbc, 225),              # the world map: 15 x 15, 1 where a path joins two pyramids
    ("kMapEdge", 0x481f40, 225),               # the world map: 15 x 15, the number of the path between two pyramids (negative: walked backwards)
    ("kMapWay", 0x4822c4, 252),                # the world map: six waypoints (x, y) per path, path numbers 1 to 19 (path n starts at pair 6n)
    ("kTutorialMove", 0x48f34c, 67),          # per tutorial step: the one move that is allowed (0 N, 1 W, 2 E, 3 S, 4 wait), 5 none, 6 and 7 the buttons
    ("kRankScore", 0x491f98, 22),             # the points at which a classic game's rank rises
]

# the tutorial's five parts: where the wall statements of each case of the switch in 0x40f520 begin, and their length
# (up to the first test after them); GameLevels.cpp decodes them
TUTORIAL = [
    (0x40f5ff, 0x1db),
    (0x40f8f5, 0xc3),
    (0x40faa6, 0x10b),
    (0x40fce6, 0x7b),
    (0x40feb4, 0x58),
]


def fnv(b):
    h = 2166136261
    for c in b:
        h = ((h ^ c) * 16777619) & 0xffffffff
    return h


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", "..", ".."))
    ap.add_argument("--exe", default=os.path.join(root, "re", "mummymaze", "bin", "WinMM.exe"))
    ap.add_argument("--out", default=os.path.join(here, "..", "src", "GameLevelsTable.inc"))
    args = ap.parse_args()
    e = Exe(args.exe)
    out = ["// Generated by games/mummymaze/tools/make_levels.py: where WinMM.exe 1.1 keeps the level data (no data).",
           "// GAMELEVEL(array, count of ints, address, FNV-1a of the bytes), TUTORIALPART(address, length, FNV-1a of the bytes)", ""]
    for name, va, n in TABLES:
        o = e.off(va)
        out.append("GAMELEVEL(%s, %d, 0x%08x, 0x%08x)" % (name, n, va, fnv(e.d[o:o + 4 * n])))
    for va, n in TUTORIAL:
        o = e.off(va)
        out.append("TUTORIALPART(0x%08x, 0x%x, 0x%08x)" % (va, n, fnv(e.d[o:o + n])))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
