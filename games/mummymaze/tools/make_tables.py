#!/usr/bin/env python3
"""Generate games/mummymaze/src/Tables.inc: the numeric tables of WinMM.exe's data section (animation offsets, the
tutorial's move constraints, the adventure's maze numbers). Numbers only; no game text.

    python games/mummymaze/tools/make_tables.py [--exe re/mummymaze/bin/WinMM.exe] [--out games/mummymaze/src/Tables.inc]
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_res import Exe

# name, address, number of 32-bit ints
TABLES = [
    ("kMummyFightX", 0x48d36c, 4 * 255),       # mummy fight/dance frames: x offset in cells, 255 frames per kind
    ("kExplorerIdleX", 0x48e35c, 4 * 255),     # the explorer's idle animations: x offset in cells per frame
    ("kTutorialMove", 0x48f34c, 67),           # per tutorial step: the one move that is allowed (0 N, 1 W, 2 E, 3 S, 4 wait), 5..7 text only
    ("kAdventureMaze", 0x48f458, 225),         # per pyramid and chamber (15 x 15): the maze file number
    ("kAdventureLevel", 0x48f7dc, 225),        # per pyramid and chamber: the maze number in the file, minus 1
    ("kExcluded", 0x48fb60, 2 * 481),  # (file, maze) pairs a classic game never picks, after a leading word
    ("kMummyIdleCount", 0x494968, 1),
    ("kMummyIdleLen", 0x49496c, 4),
    ("kExplorerIdleCount", 0x495250, 1),
    ("kExplorerIdleLen", 0x495254, 4),
    ("kMapPos", 0x481b44, 30),                 # the world map: where each of the 15 pyramids is (x, y pairs)
    ("kMapLinks", 0x481bbc, 225),              # the world map: 15 x 15, 1 where a path joins two pyramids
    ("kMapEdge", 0x481f40, 225),               # the world map: 15 x 15, the number of the path between two pyramids (negative: walked backwards)
    ("kMapWay", 0x4822c4, 252),                # the world map: six waypoints (x, y) per path, path numbers 1 to 19 (path n starts at pair 6n)
    ("kRankScore", 0x491f98, 22),              # the points at which a classic game's rank rises
]

# tables of pointers to texts: name, address of the table, count (written as the texts' addresses)
POINTER_TABLES = [
    ("kRankText", 0x491ff0, 23),               # the rank names
    ("kTreasureText", 0x494ab8, 15),           # the treasure of each pyramid, in the sentence "YOU HAVE FOUND THE ...!"
]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", "..", ".."))
    ap.add_argument("--exe", default=os.path.join(root, "re", "mummymaze", "bin", "WinMM.exe"))
    ap.add_argument("--out", default=os.path.join(here, "..", "src", "Tables.inc"))
    args = ap.parse_args()
    e = Exe(args.exe)
    out = ["// Generated by games/mummymaze/tools/make_tables.py from WinMM.exe's data section: numbers only.", ""]
    for name, va, n in TABLES:
        vals = [struct.unpack("<i", struct.pack("<I", e.u32(va + 4 * i)))[0] for i in range(n)]
        out.append("static const int %s[%d] =" % (name, n))
        out.append("{")
        for i in range(0, n, 16):
            out.append("\t" + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    for name, va, n in POINTER_TABLES:
        vals = [e.u32(va + 4 * i) for i in range(n)]
        out.append("static const unsigned %s[%d] =" % (name, n))
        out.append("{")
        for i in range(0, n, 8):
            out.append("\t" + ", ".join("0x%08x" % v for v in vals[i:i + 8]) + ",")
        out.append("};")
        out.append("")
    open(args.out, "w", newline="\n").write("\n".join(out))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
