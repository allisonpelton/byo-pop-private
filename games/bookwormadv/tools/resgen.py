#!/usr/bin/env python3
"""Lists the resource globals of BookwormAdventures.exe: the Extract<Group>Resources functions fetch each resource
by its id (ResourceManager::GetImageThrow, GetFontThrow, GetSoundThrow through the vtable) and store it in a global.
Prints `function global kind id` per resource, or with -h the declarations for games/bookwormadv/src/Res.h.

    python games/bookwormadv/tools/resgen.py            # the table
    python games/bookwormadv/tools/resgen.py -h         # Res.h's globals, grouped by function
    python games/bookwormadv/tools/resgen.py -w games/bookwormadv/src   # writes Res.h and Res.cpp there
    python games/bookwormadv/tools/resgen.py -s         # writes docs/symbols/30_res.jsonl (names for decread)

The ids are the resource names of the game's resources.xml (identifiers, not text); the table maps the
addresses the decompiled code uses to them.
"""
import json
import os
import re
import subprocess
import sys

EXE = 're/bookwormadv/bin/BookwormAdventures.exe'
OBJDUMP = 'E:/retools/llvm-mingw-20261006-ucrt-x86_64/bin/llvm-objdump.exe'
GH = 're/bookwormadv/gh'
funcs = {int(j['addr'], 16): j for j in map(json.loads, open(os.path.join(GH, 'functions.jsonl'), encoding='utf-8'))}
strs = {}
for j in map(json.loads, open(os.path.join(GH, 'strings.jsonl'), encoding='utf-8')):
    if j.get('type') == 'string':
        strs[int(j['addr'], 16)] = j['value']


def disasm(start, stop):
    out = subprocess.run([OBJDUMP, '-d', '--no-show-raw-insn', '-M', 'intel', '--start-address=%#x' % start,
                          '--stop-address=%#x' % stop, EXE], capture_output=True, text=True).stdout
    for ln in out.splitlines():
        m = re.match(r'\s*([0-9a-f]+):\s+(.*)', ln)
        if m:
            yield int(m.group(1), 16), m.group(2)

# Extract<Group>Resources, in the order ExtractResourcesByName (0x4aead0) tests the names
GROUPS = [(0x4aedc0, 'CommonGame'), (0x4b3090, 'Credits'), (0x4b3150, 'HallOfFame'), (0x4b3810, 'Init'),
          (0x4b4500, 'MiniGameCommon'), (0x4b4d20, 'MiniGameMenu'), (0x4b4ef0, 'StatsBook'), (0x4b5810, 'TitleAndMM'),
          (0x4b6340, 'UpsellTrailer')]
FUNCS = [a for a, _ in GROUPS]
# left out of Res.h and Res.cpp: what only the trial used (its upsell trailer, the main menu's "buy now"); the port
# plays as the registered game, which never asks for them
TRIAL_ONLY = {'UpsellTrailer', 'SOUND_MM_BUY_NOW'}
TYPES = {'image': 'Image*', 'font': 'Font*', 'sound': 'int'}
# the vtable slots (byte offsets) of ResourceManager the functions call
SLOTS = {0x40: 'image', 0x44: 'sound', 0x48: 'font'}


def scan(fa):
    f = funcs[fa]
    out = []
    cur = None
    slot = None
    for a, text in disasm(fa, fa + f['size']):
        m = re.match(r'push\s+0x([0-9a-f]+)', text)
        if m and int(m.group(1), 16) in strs and re.match(r'(IMAGE|FONT|SOUND)_\w+$', strs[int(m.group(1), 16)]):
            cur = strs[int(m.group(1), 16)]
            slot = None
            continue
        m = re.match(r'mov\s+\w+, dword ptr \[\w+ \+ 0x([0-9a-f]+)\]', text)
        if m and cur and int(m.group(1), 16) in SLOTS:
            slot = SLOTS[int(m.group(1), 16)]
            continue
        m = re.match(r'mov\s+(?:dword|byte) ptr \[0x([0-9a-f]+)\], (eax|al)', text)
        if m and cur:
            out.append((int(m.group(1), 16), slot or '?', cur))
            cur = None
    return out


HEADER = """// Generated by games/bookwormadv/tools/resgen.py from BookwormAdventures.exe: the resource globals of
// Extract<Group>Resources (0x4aedc0-0x4b6340) and ExtractResourcesByName (0x4aead0), as PopCap's ResGen made them.
// The ids are the names of the resources in properties/resources.xml.
"""


def write_files(rows, hpath, cpath):
    T = '\t'
    h = [HEADER + '#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class ResourceManager;',
         '', 'bool ExtractResourcesByName(ResourceManager* theManager, const char* theName);', '']
    c = [HEADER + '#include "Res.h"', '', '#include <cstring>', '', '#include "ResourceManager.h"', '',
         'using namespace Sexy;', '', 'bool gNeedRecalcVariableToIdMap = false;  // 0x82592f']
    groups = [(fa, group) for fa, group in GROUPS if group not in TRIAL_ONLY]
    for fa, group in groups:
        mine = [r for r in rows if r[0] == fa and r[3] not in TRIAL_ONLY]
        h.append('// %s (%#x)' % (group, fa))
        h.append('bool Extract%sResources(ResourceManager* theManager);' % group)
        h += ['extern %s %s;  // %#x' % (TYPES[kind], rid, g) for _, g, kind, rid in mine]
        h.append('')
        c.append('')
        c += ['%s Sexy::%s = %s;' % (TYPES[kind], rid, '0' if kind == 'sound' else 'nullptr') for _, _, kind, rid in mine]
        c += ['', 'bool Sexy::Extract%sResources(ResourceManager* theManager)' % group, '{',
              T + 'gNeedRecalcVariableToIdMap = true;', T + 'ResourceManager& aMgr = *theManager;', T + 'try {']
        for _, g, kind, rid in mine:
            call = {'image': 'GetImageThrow', 'font': 'GetFontThrow', 'sound': 'GetSoundThrow'}[kind]
            c.append(T + T + '%s = aMgr.%s("%s");' % (rid, call, rid))
        c += [T + '} catch (ResourceManagerException&) {', T + T + 'return false;', T + '}', T + 'return true;', '}']
    h.append('}  // namespace Sexy')
    c += ['', 'bool Sexy::ExtractResourcesByName(ResourceManager* theManager, const char* theName)', '{']
    for fa, group in groups:
        c += [T + 'if (strcmp(theName, "%s") == 0)' % group, T + T + 'return Extract%sResources(theManager);' % group]
    c += [T + 'return false;', '}']
    open(hpath, 'w', newline='\n').write('\n'.join(h) + '\n')
    open(cpath, 'w', newline='\n').write('\n'.join(c) + '\n')


def main():
    rows = []
    for fa in FUNCS:
        for g, kind, rid in scan(fa):
            rows.append((fa, g, kind, rid))
    if '-w' in sys.argv:
        d = sys.argv[sys.argv.index('-w') + 1]
        write_files(rows, os.path.join(d, 'Res.h'), os.path.join(d, 'Res.cpp'))
        return
    if '-s' in sys.argv:
        with open('games/bookwormadv/docs/symbols/30_res.jsonl', 'w', newline='\n') as f:
            f.write('// The resource globals (tools/resgen.py -s): Res.h\n')
            for _, g, kind, rid in rows:
                f.write('{"addr": "%08x", "name": "%s"}\n' % (g, rid))
        return
    if '-h' in sys.argv:
        for fa in FUNCS:
            print('// %#x' % fa)
            for f, g, kind, rid in rows:
                if f == fa:
                    t = {'image': 'Image*', 'font': 'Font*', 'sound': 'int'}.get(kind, '?')
                    print('extern %s %s;  // %#x' % (t, rid, g))
        return
    for f, g, kind, rid in rows:
        print('%#x %#x %s %s' % (f, g, kind, rid))


if __name__ == '__main__':
    main()
