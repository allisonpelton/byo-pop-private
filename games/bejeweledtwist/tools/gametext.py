#!/usr/bin/env python3
"""Generate games/bejeweledtwist/src/GameTextTable.inc: where each text the port uses is in the exe.

The port carries no game text (games/bejeweledtwist/src/GameText.h): it reads each one from the player's own
BejeweledTwist.exe by address. The addresses are the GT(0x...), GTC(0x...) and GTA(0x...) uses in the port's sources;
the output holds only addresses, lengths and hashes.

    python games/bejeweledtwist/tools/gametext.py [--exe re/bejeweledtwist/bin/BejeweledTwist.exe]
        [--out games/bejeweledtwist/src/GameTextTable.inc]
"""
import argparse
import glob
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
GAME = os.path.join(ROOT, "games", "bejeweledtwist")


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + min(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "bejeweledtwist", "bin", "BejeweledTwist.exe"))
    ap.add_argument("--out", default=os.path.join(GAME, "src", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    used = set()
    for pattern in ("*.cpp", "*.h"):
        for path in glob.glob(os.path.join(GAME, "**", pattern), recursive=True):
            for m in re.finditer(r"\bGT[CAS]?\(0x([0-9a-fA-F]{6,8})\)", open(path, encoding="utf-8").read()):
                used.add(int(m.group(1), 16))
    out = ["// Generated by games/bejeweledtwist/tools/gametext.py. The hard-coded texts of Bejeweled Twist",
           "// that the port uses: address in the game image, length and FNV-1a hash (GAMETEXTW: a UTF-16 text, its",
           "// length in bytes). The texts themselves are read from the player's own BejeweledTwist.exe at start-up",
           "// (GameText.h); none are in the repository."]
    todo = os.path.join(HERE, "gt_todo.txt")
    if os.path.isfile(todo):
        skip = {int(l.strip(), 16) for l in open(todo) if l.strip().startswith("0x")}
        used -= skip
    for va in sorted(used):
        o = va_to_off(d, va)
        if d[o] != 0 and d[o + 1] == 0 and d[o + 2] != 0 and d[o + 3] == 0:
            # A wide (UTF-16) text: the original's L"..."; its length in bytes
            n = o
            while d[n] != 0 or d[n + 1] != 0:
                n += 2
            s = d[o:n]
            out.append("GAMETEXTW(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
            continue
        s = d[o:d.index(b"\0", o)]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(used), os.path.relpath(args.out, ROOT)))


if __name__ == "__main__":
    sys.exit(main())
