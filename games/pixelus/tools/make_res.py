#!/usr/bin/env python3
"""Generate games/pixelus/src/Res.h and Res.cpp: Pixelus's resource tables (file names and ids).

Pixelus has no ResourceManager: the app keeps four file-name tables in its data section and every image, sound,
song and font is used by its index in them (mImages[4] is the dialog image, PlaySample(5) a tile moving). The
tables are read from the carved game image (re/pixelus/bin/PixelusGame.exe, git-ignored):

    images   0x53d768   236 entries of 8 bytes: name pointer, load group (which screen's loading step takes it)
    sounds   0x53dec8    28 entries of 4 bytes
    music    0x53df38     4 entries of 4 bytes
    fonts    0x53df48    16 entries of 4 bytes

    python games/pixelus/tools/make_res.py [--exe re/pixelus/bin/PixelusGame.exe] [--out games/pixelus/src]
"""
import argparse
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))

TABLES = [("image", 0x53D768, 236, 8), ("sound", 0x53DEC8, 28, 4), ("music", 0x53DF38, 4, 4), ("font", 0x53DF48, 16, 4)]


REGISTRATION_IMAGES = ("register",)


class Image:
    def __init__(self, path):
        self.d = open(path, "rb").read()
        pe = struct.unpack_from("<I", self.d, 0x3C)[0]
        opt = struct.unpack_from("<H", self.d, pe + 20)[0]
        self.secs = []
        for i in range(struct.unpack_from("<H", self.d, pe + 6)[0]):
            s = pe + 24 + opt + i * 40
            vs, rva, rs, rp = struct.unpack_from("<IIII", self.d, s + 8)
            self.secs.append((0x400000 + rva, max(vs, rs), rp))

    def off(self, va):
        for v, n, rp in self.secs:
            if v <= va < v + n:
                return rp + va - v
        raise ValueError(hex(va))

    def u32(self, va):
        return struct.unpack_from("<I", self.d, self.off(va))[0]

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)].decode("latin1")


def ident(prefix, name):
    base = os.path.splitext(name.replace("\\", "/").split("/")[-1])[0] if prefix != "IMAGE" else name
    base = os.path.splitext(base)[0] if prefix == "IMAGE" and base.lower().endswith((".jpg", ".png", ".gif")) else base
    return prefix + "_" + re.sub(r"[^A-Za-z0-9]+", "_", base).strip("_").upper()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "pixelus", "bin", "PixelusGame.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "pixelus", "src"))
    args = ap.parse_args()
    img = Image(args.exe)

    tables = {}
    for kind, va, n, stride in TABLES:
        rows = []
        for i in range(n):
            name = img.cstr(img.u32(va + i * stride))
            group = img.u32(va + i * stride + 4) if stride == 8 else 0
            rows.append((name, group))
        tables[kind] = rows

    h = ["#ifndef __PIXELUS_RES_H__", "#define __PIXELUS_RES_H__", "",
         "// Pixelus Deluxe's ids: images, sounds, music and fonts (generated by games/pixelus/tools/make_res.py from the",
         "// four file-name tables in the original's data section; the ids are the tables' indexes, as the original's",
         "// code uses them: mImages[IMAGE_DIALOG], PlaySample(SOUND_...), mFonts[FONT_...]).", "",
         "namespace Sexy", "{", ""]
    c = ["#include \"Res.h\"", "", "// Generated by games/pixelus/tools/make_res.py (Pixelus.exe 1.0's file-name tables).", "",
         "namespace Sexy", "{", ""]
    used = set()
    for kind, prefix in (("image", "IMAGE"), ("sound", "SOUND"), ("music", "MUSIC"), ("font", "FONT")):
        h.append("enum %sId" % prefix.capitalize())
        h.append("{")
        for i, (name, group) in enumerate(tables[kind]):
            ident_name = ident(prefix, name)
            while ident_name in used:
                ident_name += "_"
            used.add(ident_name)
            h.append("\t%s = %d," % (ident_name, i))
        h.append("\tNUM_%sS = %d" % (prefix, len(tables[kind])))
        h.append("};")
        h.append("")
        c.append("const char* const gPixelus%sNames[NUM_%sS] =" % (kind.capitalize(), prefix))
        c.append("{")
        for name, group in tables[kind]:
            if kind == "image" and name in REGISTRATION_IMAGES:
                name = ""   # only the register dialog of an unregistered copy uses it: its id stays, it is not loaded
            c.append("\t\"%s\"," % name.replace("\\", "\\\\"))
        c.append("};")
        c.append("")
        h.append("extern const char* const gPixelus%sNames[NUM_%sS];" % (kind.capitalize(), prefix))
        h.append("")
    # image load groups
    h.append("// The load group of each image (the original's second table column: which loading step takes it)")
    h.append("extern const unsigned char gPixelusImageGroups[NUM_IMAGES];")
    h.append("")
    c.append("const unsigned char gPixelusImageGroups[NUM_IMAGES] =")
    c.append("{")
    row = []
    for name, group in tables["image"]:
        row.append(str(group))
    for k in range(0, len(row), 32):
        c.append("\t" + ", ".join(row[k:k + 32]) + ",")
    c.append("};")
    c.append("")
    h += ["}", "", "#endif", ""]
    c += ["}", ""]
    open(os.path.join(args.out, "Res.h"), "w", newline="\n").write("\n".join(h))
    open(os.path.join(args.out, "Res.cpp"), "w", newline="\n").write("\n".join(c))
    print("wrote Res.h and Res.cpp: %s" % ", ".join("%d %ss" % (len(v), k) for k, v in tables.items()))


if __name__ == "__main__":
    sys.exit(main())
