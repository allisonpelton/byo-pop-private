#!/usr/bin/env python3
"""Writes src/Res.h and src/Res.cpp, the resource globals of Peggle Deluxe, as the exe's own ResGen output has them:
the id of every resource (the order of the exe's name table, 0x403930), one global per resource (an Image*, a Font* or
an int for a sound), and one Extract<Group>Resources function for each <Resources> group of properties/resources.xml,
which loads the group's resources through the ResourceManager in the order the exe does (sorted by full id within a
group). Also writes re/peggle/deluxe/res_map.txt, the address of each global and its id, for reading the export. The
ids are identifiers, not text.

    python -I games/peggle/tools/resgen.py

Reads the export in re/peggle/deluxe/gh, the exe in re/peggle/deluxe/bin and the staged properties/resources.xml
(tools/stage_peggle_assets.py).
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
GH = os.path.join(ROOT, 're', 'peggle', 'deluxe', 'gh')
EXE = os.path.join(ROOT, 're', 'peggle', 'deluxe', 'bin', 'PeggleGame.exe')
XML = os.path.join(ROOT, 'assets', 'peggle', 'properties', 'resources.xml')
NAME_TABLE_FN = '00403930'   # case N: return "IMAGE_SCREENFRAMELEFT"
GLOBAL_TABLE = 0x649010      # PTR_DAT_00649010: the address of each id's global
STRING_ASSIGN = 'FUN_0040cea0'
GROUPS = [('Adventure', '004129f0'), ('Character', '00412b20'), ('Dialog', '004130b0'), ('Game', '00414210'),
          ('Help', '004161e0'), ('IP', '004163d0'), ('Init', '00416cb0'), ('Interface', '00417290'),
          ('LevelSelect', '00417ea0'), ('Load', '004183d0'), ('LoadingThread', '00418900'), ('LuckySpin', '0041a000'),
          ('MainMenu', '0041a420'), ('Story', '0041abf0'), ('Upsell', '0041adf0')]
KINDS = {'image': 'Image*', 'font': 'Font*', 'sound': 'int'}
GETTER = {'image': 'GetImageThrow', 'font': 'GetFontThrow', 'sound': 'GetSoundThrow'}
HEADER = ['// Generated by games/peggle/tools/resgen.py from the exe\'s resource id table (0x403930) and its group',
          '// functions (0x4129f0-0x41adf0): the resource globals and their ids, as the exe\'s ResGen output has them.',
          '// The ids are the names of the resources in properties/resources.xml.']


def function_text(address):
    text = open(os.path.join(GH, 'all.c'), encoding='utf-8', errors='replace').read()
    start = text.find('// %s  ' % address)
    if start < 0:
        sys.exit('no decompilation of ' + address)
    end = text.find('\n// 0', start + 10)
    return text[start:end if end > 0 else len(text)]


def file_offset(data, address):
    header = struct.unpack_from('<I', data, 0x3C)[0]
    count = struct.unpack_from('<H', data, header + 6)[0]
    optional = struct.unpack_from('<H', data, header + 20)[0]
    base = struct.unpack_from('<I', data, header + 24 + 28)[0]
    section = header + 24 + optional
    for index in range(count):
        virtual_size, virtual, raw_size, raw = struct.unpack_from('<IIII', data, section + index * 40 + 8)
        if virtual <= address - base < virtual + min(virtual_size, raw_size):
            return raw + address - base - virtual
    raise ValueError(hex(address))


def resource_groups(xml):
    """For each <Resources> group: its resources as (id, kind), the id being the group's idprefix and the tag's id."""
    groups = {}
    for group in re.finditer(r'<Resources\s+id="([^"]+)"\s*>(.*?)</Resources>', xml, re.S):
        prefix = ''
        items = []
        for tag in re.finditer(r'<(SetDefaults|Image|Font|Sound)\b([^>]*)>', group.group(2)):
            attributes = dict(re.findall(r'(\w+)="([^"]*)"', tag.group(2)))
            if tag.group(1) == 'SetDefaults':
                prefix = attributes.get('idprefix', prefix)
            else:
                items.append((prefix + attributes['id'], tag.group(1).lower()))
        groups[group.group(1)] = sorted(set(items))  # FONT_OVERLOAD24GRAD1 is defined twice in LoadingThread; the exe loads it once
    return groups


def main():
    ids = []
    for case in re.finditer(r'case (0x[0-9a-f]+|\d+):\s*return "([A-Z0-9_]+)";', function_text(NAME_TABLE_FN)):
        assert int(case.group(1), 0) == len(ids)
        ids.append(case.group(2))
    data = open(EXE, 'rb').read()
    addresses = [struct.unpack_from('<I', data, file_offset(data, GLOBAL_TABLE + 4 * index))[0] for index in range(len(ids))]
    xml_groups = resource_groups(open(XML, encoding='utf-8-sig', errors='replace').read())
    kind = {}
    groups = []
    for group, address in GROUPS:
        items = xml_groups[group]
        seen = re.findall(re.escape(STRING_ASSIGN) + r'\("([A-Z0-9_]+)"', function_text(address))
        names = [name for name, _ in items]
        position = 0
        for name in seen:
            if name not in names[position:]:
                sys.exit('%s: the exe loads %s out of the sorted order of resources.xml' % (group, name))
            position = names.index(name, position) + 1
        for name, item_kind in items:
            if kind.setdefault(name, item_kind) != item_kind:
                sys.exit('%s is both %s and %s' % (name, kind[name], item_kind))
        groups.append((group, items))
    total = sum(len(items) for _, items in groups)
    if total != len(ids) or set(kind) != set(ids):
        sys.exit('%d ids but %d loaded; only in the table: %s; only in the groups: %s'
                 % (len(ids), total, sorted(set(ids) - set(kind))[:5], sorted(set(kind) - set(ids))[:5]))

    header = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class ResourceManager;', '',
                       'enum ResourceId {']
    header += ['\t%s_ID,' % name for name in ids]
    header += ['\tRESOURCE_ID_MAX', '};', '']
    source = HEADER + ['#include "Res.h"', '', '#include "ResourceManager.h"', '#include "Font.h"', '',
                       'using namespace Sexy;', '']
    for name in ids:
        source.append('%s Sexy::%s = %s;' % (KINDS[kind[name]], name, '0' if kind[name] == 'sound' else 'nullptr'))
    source.append('')
    for group, items in groups:
        header.append('// %s: 0x%x' % (group, int(dict(GROUPS)[group], 16)))
        header.append('bool Extract%sResources(ResourceManager* theManager);' % group)
        for name, item_kind in items:
            header.append('extern %s %s;' % (KINDS[item_kind], name))
        header.append('')
        source += ['bool Sexy::Extract%sResources(ResourceManager* theManager)' % group, '{', '\ttry {']
        for name, item_kind in items:
            source.append('\t\t%s = theManager->%s("%s");' % (name, GETTER[item_kind], name))
        source += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
    header.append('}  // namespace Sexy')
    with open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='') as handle:
        handle.write('\n'.join(header) + '\n')
    with open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='') as handle:
        handle.write('\n'.join(source))
    with open(os.path.join(ROOT, 're', 'peggle', 'deluxe', 'res_map.txt'), 'w') as handle:
        for name, address in zip(ids, addresses):
            handle.write('%08x %s\n' % (address, name))
    print('%d resources in %d groups; Res.h, Res.cpp, res_map.txt written' % (len(ids), len(groups)))


main()
