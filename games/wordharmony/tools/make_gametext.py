#!/usr/bin/env python3
"""Generate games/wordharmony/game/GameTextTable.inc: where each text of Word Harmony's exe that the port uses is.

The port carries no game text (games/wordharmony/game/GameText.h): it reads the texts it shows from the player's own
WordHarmony.exe by address. This lists the addresses that engine/, game/ and src/ name with GT(0x...), with each
text's length and hash, read from the carved game image (re/wordharmony/bin/WordHarmonyGame.exe, git-ignored). Run it
again after adding a GT().

    python games/wordharmony/tools/make_gametext.py [--exe re/wordharmony/bin/WordHarmonyGame.exe]
        [--out games/wordharmony/game/GameTextTable.inc]
"""
import argparse
import glob
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
GAME = os.path.join(ROOT, "games", "wordharmony")
DIRS = ["engine", "game", "src"]


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + rs:
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "wordharmony", "bin", "WordHarmonyGame.exe"))
    ap.add_argument("--out", default=os.path.join(GAME, "game", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    vas = set()
    paths = []
    for sub in DIRS:
        paths += glob.glob(os.path.join(GAME, sub, "*.cpp")) + glob.glob(os.path.join(GAME, sub, "*.h"))
    for path in paths:
        for m in re.finditer(r"\bGT\((0x[0-9a-fA-F]+)\)", open(path, encoding="utf-8").read()):
            vas.add(int(m.group(1), 16))
    out = ["// Generated by games/wordharmony/tools/make_gametext.py. The texts of WordHarmony.exe that the port uses:",
           "// address in the game image, length and FNV-1a hash. The texts themselves are read from the player's own",
           "// WordHarmony.exe at start-up (GameText.h); none are in the repository."]
    for va in sorted(vas):
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(vas), args.out))


if __name__ == "__main__":
    sys.exit(main())
