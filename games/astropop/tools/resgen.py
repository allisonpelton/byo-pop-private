#!/usr/bin/env python3
"""Writes src/Res.h and src/Res.cpp, the resource globals of AstroPop Deluxe, as the exe's own ResGen output has them
(2004 SexyApp ResGen: an enum of every resource id, the table from id to global GetImageById/GetFontById/GetSoundById
(0x4092c0 and its neighbours), the name of each id (GetStringIdById, 0x4092e0), one Extract<Group>Resources function per
<Resources> group and ExtractResourcesByName (0x422f20)).

The ids and their order come from the exe (the case table of GetStringIdById, read from the Ghidra export in
re/astropop/gh/decomp: ids are identifiers, not text); each group's members from properties/resources.xml, whose
<SetDefaults idprefix="..."/> gives the prefix of the ids that follow it. The exe has 690 ids; the xml has a few more
elements than ids (the ones the exe never extracts).

    python games/astropop/tools/resgen.py [--xml assets/astropop/properties/resources.xml]
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
KINDS = {'Image': 'Image*', 'Font': 'Font*', 'Sound': 'int'}
GETTER = {'Image': 'GetImageThrow', 'Font': 'GetFontThrow', 'Sound': 'GetSoundThrow'}
HEADER = ['// Generated by games/astropop/tools/resgen.py from the exe\'s resource id table and properties/resources.xml:',
          '// the resource globals and their ids, as the exe\'s ResGen output has them. The ids are the names of the',
          '// resources in that file.']


def exe_ids():
    p = glob.glob(os.path.join(ROOT, 're', 'astropop', 'gh', 'decomp', '_global', '004092e0_*.c'))[0]
    t = open(p, encoding='utf-8', errors='replace').read()
    pairs = re.findall(r'case (0x[0-9a-f]+|\d+):\s*return "([^"]*)"', t)
    ids = [None] * len(pairs)
    for n, name in pairs:
        ids[int(n, 0)] = name
    if None in ids:
        sys.exit('gap in the id table')
    return ids


def group_functions():
    """The address of each group's own function, read from ExtractResourcesByName (0x422f20): the name it compares with, then
    the call of the group's function."""
    p = glob.glob(os.path.join(ROOT, 're', 'astropop', 'gh', 'decomp', '_global', '00422f20_*.c'))[0]
    t = open(p, encoding='utf-8', errors='replace').read()
    return dict(re.findall(r'pcVar4 = "([^"]+)";.*?FUN_([0-9a-f]{8})\(param_1\)', t, re.S))


def xml_groups(path):
    text = open(path, encoding='utf-8-sig').read()
    groups = []
    for m in re.finditer(r'<Resources\s+id="([^"]+)"\s*>(.*?)</Resources>', text, re.S):
        prefix = ''
        items = []
        for e in re.finditer(r'<(SetDefaults|Image|Font|Sound)\b([^>]*)>', m.group(2)):
            kind, attrs = e.group(1), e.group(2)
            if kind == 'SetDefaults':
                pm = re.search(r'idprefix="([^"]*)"', attrs)
                if pm:
                    prefix = pm.group(1)
                continue
            im = re.search(r'\bid="([^"]+)"', attrs)
            if im:
                items.append((kind, prefix + im.group(1)))
        groups.append((m.group(1), items))
    return groups


def check():
    """Each group's function in the port against the exe's (the coverage check read all 44 again): the same resources, taken by
    name in the exe's order, each with the getter of its kind."""
    getter = {'IMAGE': 'GetImageThrow', 'FONT': 'GetFontThrow', 'SOUND': 'GetSoundThrow'}
    cpp = open(os.path.join(SRC, 'Res.cpp'), encoding='utf-8').read()
    bad = 0
    addresses = group_functions()
    for g, a in sorted(addresses.items()):
        m = re.search(r'bool Sexy::Extract%sResources\(ResourceManager\* theManager\)\n\{\n(.*?)\n\}\n' % g, cpp, re.S)
        port = re.findall(r'= theManager->(\w+)\("([A-Z0-9_]+)"\)', m.group(1)) if m else []
        p = glob.glob(os.path.join(ROOT, 're', 'astropop', 'gh', 'decomp', '_global', a + '_*.c'))[0]
        text = open(p, encoding='utf-8', errors='replace').read()
        exe = []
        for n in re.findall(r'"((?:IMAGE|FONT|SOUND)_[A-Z0-9_]+)"', text):
            if not exe or exe[-1] != n:
                exe.append(n)
        if exe != [n for _, n in port] or any(k != getter[n.split('_')[0]] for k, n in port):
            bad += 1
            print('differs: %s (0x%s)' % (g, a))
    print('%d groups, %d differ from the exe' % (len(addresses), bad))
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--xml', default=os.path.join(ROOT, 'assets', 'astropop', 'properties', 'resources.xml'))
    ap.add_argument('--check', action='store_true', help="compare Res.cpp's group functions with the exe's and exit")
    args = ap.parse_args()
    if args.check:
        sys.exit(1 if check() else 0)
    ids = exe_ids()
    groups = xml_groups(args.xml)
    kind = {}
    for g, items in groups:
        for k, rid in items:
            if kind.setdefault(rid, k) != k:
                sys.exit('%s is both %s and %s' % (rid, kind[rid], k))
    idset = set(ids)
    only_exe = [r for r in ids if r not in kind]
    only_xml = [r for r in kind if r not in idset]
    if only_exe:
        sys.exit('ids only in the exe: %s' % ' '.join(only_exe))
    if only_xml:
        print('xml elements the exe has no id for: %s' % ' '.join(only_xml))

    h = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class ResourceManager;', '',
                  'enum ResourceId {']
    h += ['\t%s_ID,' % rid for rid in ids]
    h += ['\tRESOURCE_ID_MAX', '};', '',
          'bool ExtractResourcesByName(ResourceManager* theManager, const char* theName);  // 0x422f20',
          'Image* GetImageById(int theId);               // 0x4092c0',
          'Font* GetFontById(int theId);',
          'int GetSoundById(int theId);',
          'const char* GetStringIdById(int theId);       // 0x4092e0',
          'Image* LoadImageById(ResourceManager* theManager, int theId);   // 0x420ea0 (loads the picture again if it was deleted)', '']
    c = HEADER + ['#include "Res.h"', '', '#include <cstring>', '#include "ResourceManager.h"', '',
                  'using namespace Sexy;', '']
    for rid in ids:
        c.append('%s Sexy::%s = %s;' % (KINDS[kind[rid]], rid, '0' if KINDS[kind[rid]] == 'int' else 'nullptr'))
    c += ['', 'namespace {', '', 'void* const gResources[RESOURCE_ID_MAX] = {']
    c += ['\t&%s,' % rid for rid in ids]
    c += ['};', '', 'const char* const gResourceNames[RESOURCE_ID_MAX] = {']
    c += ['\t"%s",' % rid for rid in ids]
    c += ['};', '', '}  // namespace', '',
          'Image* Sexy::GetImageById(int theId) { return *(Image**)gResources[theId]; }',
          'Font* Sexy::GetFontById(int theId) { return *(Font**)gResources[theId]; }',
          'int Sexy::GetSoundById(int theId) { return *(int*)gResources[theId]; }',
          'const char* Sexy::GetStringIdById(int theId) { return (unsigned)theId < RESOURCE_ID_MAX ? gResourceNames[theId] : ""; }',
          '',
          '// 0x420ea0: the picture of a resource id, loaded again by name if it was deleted; the id\'s global holds it afterwards',
          'Image* Sexy::LoadImageById(ResourceManager* theManager, int theId)',
          '{',
          '\tImage* anImage = theManager->LoadImage(GetStringIdById(theId));   // (0x4923a0 loads the picture if it is not loaded)',
          '\t*(Image**)gResources[theId] = anImage;',
          '\treturn *(Image**)gResources[theId];',
          '}',
          '']

    done = set()
    addresses = group_functions()
    for g, items in groups:
        h.append('// %s' % g)
        h.append('bool Extract%sResources(ResourceManager* theManager);' % g)
        for k, rid in items:
            if rid in idset and rid not in done:
                done.add(rid)
                h.append('extern %s %s;' % (KINDS[k], rid))
        h.append('')
        if g in addresses:
            c.append('// 0x%s: the resource group "%s" (the original has a function of its own for each group and a switch by name, 0x422f20)'
                     % (addresses[g].lstrip('0'), g))
        c += ['bool Sexy::Extract%sResources(ResourceManager* theManager)' % g, '{', '\ttry {']
        for k, rid in sorted(items, key=lambda kr: kr[1]):    # the exe's function takes its resources by name (checked: all 44 groups)
            if rid in idset:
                c.append('\t\t%s = theManager->%s("%s");' % (rid, GETTER[k], rid))
        c += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
    h.append('}  // namespace Sexy')
    c += ['bool Sexy::ExtractResourcesByName(ResourceManager* theManager, const char* theName)', '{']
    for g, _ in groups:
        c += ['\tif (strcmp(theName, "%s") == 0)' % g, '\t\treturn Extract%sResources(theManager);' % g]
    c += ['\treturn false;', '}', '']
    open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='').write('\n'.join(h) + '\n')
    open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    print('%d ids, %d groups -> Res.h, Res.cpp' % (len(ids), len(groups)))


if __name__ == '__main__':
    main()
