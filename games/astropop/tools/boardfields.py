#!/usr/bin/env python3
"""Keeps the member list of Board.h in step with the table of its fields.

The Board is a god object (sizeof 0x1c0c in the original). docs/board_fields.tsv holds one line per member,

    offset(hex) <TAB> type <TAB> name <TAB> comment

in the order of the original's object, and this script rewrites the part of Board.h between the BEGIN FIELDS and
END FIELDS markers from the table, in offset order, with a default initialiser for scalar types. Every member
has its name; the offset stays in the table and in the comment of the declaration. Renaming a member: change the
name column, replace the name in the sources (whole word; a name that other classes also use needs the compiler
to find the uses, see GAME_NOTES section 12), and run this script. Taking a member out: delete its line.

    python games/astropop/tools/boardfields.py [--add]

--add also adds a line (type int, name m<offset>) for every `m<hex offset>` token in src/Board*.cpp that the table
does not know (for a decompilation step that meets a field not yet in the table); a word such as "made" in a
comment looks like one, so it is not done by default.
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
SRC = os.path.join(ROOT, "games", "astropop", "src")
TSV = os.path.join(ROOT, "games", "astropop", "docs", "board_fields.tsv")
HDR = os.path.join(SRC, "Board.h")
BEGIN = "\t// BEGIN FIELDS (generated by tools/boardfields.py from docs/board_fields.tsv)"
END = "\t// END FIELDS"

SCALARS = {"unsigned char": "0", "int": "0", "unsigned": "0", "unsigned int": "0", "char": "0", "short": "0", "bool": "false",
           "float": "0.0f", "double": "0.0", "uint8_t": "0", "uint32_t": "0", "int8_t": "0"}


def read_table():
    rows = []
    if os.path.exists(TSV):
        for ln in open(TSV, encoding="utf-8"):
            ln = ln.rstrip("\n")
            if not ln.strip() or ln.startswith("#"):
                continue
            parts = ln.split("\t")
            while len(parts) < 4:
                parts.append("")
            rows.append(parts[:4])
    return rows


def main():
    rows = read_table()
    known = {r[2].split("[")[0] for r in rows}
    offs = {int(r[0], 16) for r in rows}
    added = []
    # rows are added only on request: a word such as "made" in a comment looks like the field at +0xade
    for f in (sorted(glob.glob(os.path.join(SRC, "Board*.cpp"))) if "--add" in sys.argv else []):
        txt = open(f, encoding="utf-8", errors="replace", newline="").read()
        for m in re.finditer(r"(?<![\w.>])m([0-9a-f]{2,4})\b", txt):
            off = int(m.group(1), 16)
            nm = "m" + m.group(1)
            if nm in known or off in offs or off >= 0x1c0c:
                continue
            rows.append(["%x" % off, "int", nm, "?"])
            known.add(nm)
            offs.add(off)
            added.append(nm)
    rows.sort(key=lambda r: int(r[0], 16))
    with open(TSV, "w", encoding="utf-8", newline="\n") as o:
        o.write("# offset\ttype\tname\tcomment  (written by tools/boardfields.py; keep it sorted by offset)\n")
        for r in rows:
            o.write("\t".join(r).rstrip() + "\n")
    out = []
    for off, ty, nm, cm in rows:
        base = ty.strip()
        if base in SCALARS and "[" not in nm:
            decl = "%s\t%s = %s;" % (base, nm, SCALARS[base])
        elif base.endswith("*") and "[" not in nm:
            decl = "%s\t%s = NULL;" % (base, nm)
        else:
            decl = "%s\t%s;" % (base, nm)
        out.append("\t%s// +0x%s%s" % (decl.ljust(0), off, (" " + cm) if cm and cm != "?" else (" ?" if cm == "?" else "")))
    h = open(HDR, encoding="utf-8", newline="").read()
    crlf = "\r\n" in h
    h = h.replace("\r\n", "\n")
    i = h.index(BEGIN)
    j = h.index(END)
    h = h[:i] + BEGIN + "\n" + "\n".join(out) + "\n" + h[j:]
    if crlf:
        h = h.replace("\n", "\r\n")
    open(HDR, "w", encoding="utf-8", newline="").write(h)
    print("%d fields, %d added: %s" % (len(rows), len(added), " ".join(added[:40])))


if __name__ == "__main__":
    main()
