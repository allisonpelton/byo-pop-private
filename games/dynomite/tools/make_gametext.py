#!/usr/bin/env python3
"""Generate games/dynomite/src/GameTextTable.inc: where each of Dynomite's hard-coded texts is in the game image.

Most of Dynomite's texts are in properties/default.xml and the port reads them with GetString. A few are hard-coded
in the exe (the modes' high-score titles, some labels); the port carries none of them (games/dynomite/src/GameText.h)
and reads them from the player's own Dynomite.exe by address. The input is gametext_vas.txt beside this script: the
addresses the translated code names with GT(0x...), one per line, with no text. The output holds only addresses,
lengths and hashes.

    python games/dynomite/tools/make_gametext.py [--exe re/dynomite/bin/DynomiteGame.exe]
        [--out games/dynomite/src/GameTextTable.inc]
"""
import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + rs:
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "dynomite", "bin", "DynomiteGame.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "dynomite", "src", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    rows = []
    for line in open(os.path.join(HERE, "gametext_vas.txt")):
        line = line.split("#")[0].strip()
        if line:
            va = int(line, 16)
            if va not in rows:
                rows.append(va)
    rows.sort()
    out = ["// Generated by games/dynomite/tools/make_gametext.py from tools/gametext_vas.txt. Dynomite Deluxe's",
           "// hard-coded strings: address in the game image, length and FNV-1a hash. The texts themselves are read",
           "// from the player's own Dynomite.exe at start-up (GameText.h); none are in the repository."]
    for va in rows:
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(rows), args.out))


if __name__ == "__main__":
    sys.exit(main())
