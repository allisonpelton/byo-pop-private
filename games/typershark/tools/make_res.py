#!/usr/bin/env python3
"""Generate games/typershark/src/Res.h and Res.cpp: Typer Shark's resource tables (file names and ids).

Typer Shark has no ResourceManager: the app keeps one table of file-name pointers in its data section (0x55f4f0) and
every image, sound and treasure name is used by its index in it. The loader walks the table in three steps:

    images    index 0..247    "images\\" + name, read by SexyApp::GetImage (0..241 by the loading screen's first
                              step, 242..245 the four cursors, by Init); stored in the app's image array
    sounds    index 248..287  "sounds\\" + name, handed to the sound manager as sound ids 0..39
    names     index 288..293  the treasure names (Emerald ... Sapphire) that the treasure screens print

The table is read from the carved game image (re/typershark/bin/TyperSharkGame.exe, git-ignored):

    python games/typershark/tools/make_res.py [--exe re/typershark/bin/TyperSharkGame.exe] [--out games/typershark/src]
"""
import argparse
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))

TABLE = 0x55F4F0
NUM_IMAGES = 248
NUM_SOUNDS = 40
NUM_NAMES = 6


class Image:
    def __init__(self, path):
        self.d = open(path, "rb").read()
        pe = struct.unpack_from("<I", self.d, 0x3C)[0]
        opt = struct.unpack_from("<H", self.d, pe + 20)[0]
        self.secs = []
        for i in range(struct.unpack_from("<H", self.d, pe + 6)[0]):
            s = pe + 24 + opt + i * 40
            vs, rva, rs, rp = struct.unpack_from("<IIII", self.d, s + 8)
            self.secs.append((0x400000 + rva, max(vs, rs), rp))

    def off(self, va):
        for v, n, rp in self.secs:
            if v <= va < v + n:
                return rp + va - v
        raise ValueError(hex(va))

    def u32(self, va):
        return struct.unpack_from("<I", self.d, self.off(va))[0]

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)].decode("latin1")


def ident(prefix, name, used):
    base = prefix + "_" + re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
    out, n = base, 2
    while out in used:
        out = "%s_%d" % (base, n)
        n += 1
    used.add(out)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "typershark", "bin", "TyperSharkGame.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "typershark", "src"))
    args = ap.parse_args()
    img = Image(args.exe)
    names = [img.cstr(img.u32(TABLE + 4 * i)) for i in range(NUM_IMAGES + NUM_SOUNDS + NUM_NAMES)]
    images = names[:NUM_IMAGES]
    sounds = names[NUM_IMAGES:NUM_IMAGES + NUM_SOUNDS]
    treasure_addrs = [img.u32(TABLE + 4 * (NUM_IMAGES + NUM_SOUNDS + i)) for i in range(NUM_NAMES)]
    treasures = names[NUM_IMAGES + NUM_SOUNDS:]
    used = set()
    h = ["// Generated by games/typershark/tools/make_res.py: the ids of the original's resource-name table (0x55f4f0).",
         "// The file names are in Res.cpp; the files themselves come from the player's own game folder.",
         "#ifndef __TYPERSHARK_RES_H__", "#define __TYPERSHARK_RES_H__", "", "namespace Sexy", "{", "", "enum ImageId", "{"]
    for i, n in enumerate(images):
        h.append("\t%s = %d," % (ident("IMAGE", n, used), i))
    h += ["\tNUM_IMAGES = %d" % NUM_IMAGES, "};", "", "enum SoundId", "{"]
    for i, n in enumerate(sounds):
        h.append("\t%s = %d," % (ident("SOUND", n, used), i))
    h += ["\tNUM_SOUNDS = %d" % NUM_SOUNDS, "};", "", "enum TreasureNameId", "{"]
    for i, n in enumerate(treasures):
        h.append("\t%s = %d," % (ident("TREASURE", "NAME%d" % i, used), i))
    h += ["\tNUM_TREASURE_NAMES = %d" % len(treasures), "};", "",
          "extern const char* const gImageNames[NUM_IMAGES];", "extern const char* const gSoundNames[NUM_SOUNDS];",
          "// the treasure names are game text: the address of each in the game image, for GT() (GameText.h)",
          "extern const unsigned int gTreasureNameAddrs[NUM_TREASURE_NAMES];", "", "}", "", "#endif", ""]
    c = ["// Generated by games/typershark/tools/make_res.py (see Res.h).", '#include "Res.h"', "", "namespace Sexy", "{", "",
         "const char* const gImageNames[NUM_IMAGES] =", "{"]
    c += ['\t"%s",' % n for n in images]
    c += ["};", "", "const char* const gSoundNames[NUM_SOUNDS] =", "{"]
    c += ['\t"%s",' % n for n in sounds]
    c += ["};", "", "const unsigned int gTreasureNameAddrs[NUM_TREASURE_NAMES] =", "{"]
    c += ["	0x%08x," % a for a in treasure_addrs]
    c += ["};", "", "}", ""]
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "Res.h"), "w", newline="\n") as f:
        f.write("\n".join(h))
    with open(os.path.join(args.out, "Res.cpp"), "w", newline="\n") as f:
        f.write("\n".join(c))
    print("Res.h/Res.cpp: %d images, %d sounds, %d treasure names" % (len(images), len(sounds), len(treasures)))


if __name__ == "__main__":
    main()
