#!/usr/bin/env python3
"""port: writes games/zumasrevenge/src/Res.h and Res.cpp, Zuma's Revenge's resource globals as the exe's ResourceGen2
output has them (0x50ae20-0x522dd0): an enum of every resource id, a global for each, the step that gives each global
to the resource manager (0x51d7e0: the manager sets a global whenever its resource loads), the id's name and back, one
Extract<Group>Resources function per <Resources> group, each taking its group's resources in the exe's order and failing
when one is missing, and ExtractResourcesByName.

The ids and their order come from the exe (GetStringIdById's jump table, 0x520cd0); each resource's kind from
properties/resources.xml; the order of the getter calls in each extraction function from the exe's own code, where each
is `mov ecx, offset <id name>` before a call of one of the five typed getters. The ids are identifiers, not text. The
Main group's function (0x519110) gets nothing from the manifest: it makes the seven 3D effects, whose sources are in the
exe (effects\\grayscale.fx and the rest); the port leaves that to the 3D mode.

    python games/zumasrevenge/tools/resgen.py [--exe assets/zumasrevenge/zumasrevengegame.exe] [--xml ...]
"""
import argparse
import collections
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
OBJDUMP = 'E:/retools/llvm-mingw-20261006-ucrt-x86_64/bin/llvm-objdump.exe'
NAME_TABLE = 0x520cd0  # GetStringIdById's jump table: each case is "mov eax, offset name; ret"
ID_MAX = 0x834
KINDS = {'Image': 'Image*', 'Font': 'Font*', 'Sound': 'int', 'PopAnim': 'PopAnim*', 'PIEffect': 'PIEffect*',
         'RenderEffect': 'RenderEffectDefinition*'}
# the exe's typed getters (manager slots 0x54 to 0x64), each of which also records the resource's id
GETTERS = {0x50b200: 'Image', 0x50b3b0: 'Sound', 0x50b2e0: 'Font', 0x50b480: 'PopAnim', 0x50b550: 'PIEffect'}
GETTER_ADDRESSES = {k: a for a, k in GETTERS.items()}
# each group's extraction function, in the manifest's order, which ExtractResourcesByName (0x50ae20) follows
EXTRACTS = [
    ('Boss1', 0x50b8b0), ('Boss2', 0x50bb80), ('Boss3', 0x50bd90), ('Boss4', 0x50c060), ('Boss5', 0x50c2c0),
    ('Boss6Common', 0x50c8b0), ('Boss6_DarkFrog', 0x50d520), ('Boss6_Lame', 0x50d720), ('Boss6_StoneHead', 0x50de80),
    ('BossIntro', 0x50dfb0), ('CommonBoss', 0x50e050), ('CommonGame', 0x50e210), ('CommonGauntlet', 0x5122d0),
    ('Credits', 0x512560), ('Distortion', 0x512750), ('Dynamic', 0x5127e0), ('Fog', 0x515860),
    ('FoliageJungle1', 0x515920), ('GrottoSounds', 0x515b90), ('Init', 0x515cb0), ('IronFrogWin', 0x516020),
    ('LandCritters', 0x5160c0), ('Levels', 0x5161d0), ('Levesl', 0x5188f0), ('LoadScreen', 0x518980),
    ('Main', 0x519110), ('MainSounds', 0x51c990), ('MenuRelated', 0x51ce60), ('ShaderNoise', 0x51d450),
    ('ShadowCanopyJungle1', 0x51d510), ('ShadowCanopyJungle2', 0x51d5d0), ('Underwater', 0x51d660),
    ('WaterEffects', 0x51d720),
]
HEADER = ['// Generated by games/zumasrevenge/tools/resgen.py from the exe\'s resource id table, properties/resources.xml and',
          '// the exe\'s extraction functions: the resource globals and their ids, as the exe\'s ResourceGen2 output has',
          '// them (0x50ae20-0x522dd0 (zumasrevenge)). The ids are the names of the resources in that file.']


class Exe:
    def __init__(self, path):
        self.path = path
        self.data = open(path, 'rb').read()
        pe = struct.unpack_from('<I', self.data, 0x3C)[0]
        nsec = struct.unpack_from('<H', self.data, pe + 6)[0]
        opt = struct.unpack_from('<H', self.data, pe + 20)[0]
        self.base = struct.unpack_from('<I', self.data, pe + 24 + 28)[0]
        self.sections = []
        for i in range(nsec):
            vs, rva, rs, ro = struct.unpack_from('<IIII', self.data, pe + 24 + opt + i * 40 + 8)
            self.sections.append((rva, min(vs, rs), ro))

    def offset(self, va):
        for rva, size, ro in self.sections:
            if rva <= va - self.base < rva + size:
                return ro + va - self.base - rva
        raise ValueError(hex(va))

    def dword(self, va):
        return struct.unpack_from('<I', self.data, self.offset(va))[0]

    def cstring(self, va):
        o = self.offset(va)
        return self.data[o:self.data.index(b'\0', o)].decode('ascii')


def exe_ids(exe):
    ids = []
    for i in range(ID_MAX):
        case = exe.dword(NAME_TABLE + 4 * i)
        o = exe.offset(case)
        if exe.data[o] != 0xB8:
            sys.exit('id %d: unexpected code at the name table' % i)
        ids.append(exe.cstring(struct.unpack_from('<I', exe.data, o + 1)[0]))
    return ids


def xml_groups(path):
    text = open(path, encoding='utf-8-sig', errors='replace').read()
    groups = collections.OrderedDict()
    kind = {}
    for m in re.finditer(r'<Resources\s+id="([^"]+)"\s*>(.*?)</Resources>', text, re.S):
        items = re.findall(r'<(Image|Font|Sound|PopAnim|PIEffect)\s+id="([^"]+)"', m.group(2))
        groups[m.group(1)] = items
        for k, rid in items:
            if kind.setdefault(rid, k) != k:
                sys.exit('%s is both %s and %s' % (rid, kind[rid], k))
    return groups, kind


def exe_calls(exe, address, ids):
    """the (kind, id name) of each getter call of the function at address, in order: each call's first stack argument,
    the immediate pushed last before it, is the resource's id"""
    out = subprocess.run([OBJDUMP, '-d', '--no-show-raw-insn', '-M', 'intel', '--start-address=%#x' % address,
                          '--stop-address=%#x' % (address + 0x10000), exe.path], capture_output=True, text=True).stdout
    calls = []
    pushed = None
    for line in out.splitlines():
        m = re.match(r'\s*([0-9a-f]+):\s+(\S+)\s*(.*)', line)
        if not m:
            continue
        op, args = m.group(2), m.group(3)
        if op == 'push' and re.fullmatch(r'0x[0-9a-f]+|\d+', args.split()[0]):
            pushed = int(args.split()[0], 0)
        elif op == 'call':
            target = re.search(r'0x([0-9a-f]+)', args)
            target = int(target.group(1), 16) if target else None
            if target in GETTERS:
                if pushed is None or pushed >= ID_MAX:
                    sys.exit('0x%x: a getter call without an id pushed before it' % address)
                calls.append((GETTERS[target], ids[pushed]))
                pushed = None
        elif op == 'ret':
            break
    return calls


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--exe', default=os.path.join(ROOT, 'assets', 'zumasrevenge', 'zumasrevengegame.exe'))
    ap.add_argument('--xml', default=os.path.join(ROOT, 'assets', 'zumasrevenge', 'properties', 'resources.xml'))
    args = ap.parse_args()
    exe = Exe(args.exe)
    ids = exe_ids(exe)
    groups, kind = xml_groups(args.xml)
    for rid in ids:
        if rid.startswith('EFFECT_'):
            kind[rid] = 'RenderEffect'  # the Main group's seven effects, which the manifest does not list
    missing = [r for r in ids if r not in kind] + [r for r in kind if r not in set(ids)]
    if missing:
        sys.exit('ids in only one of the exe and the xml: %s' % ' '.join(missing))
    if [g for g, _ in EXTRACTS] != list(groups):
        sys.exit('the manifest\'s groups are not the extraction functions\' (%s)' % ' '.join(groups))

    by_kind = collections.Counter(kind[r] for r in ids)
    h = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class PopAnim;', 'class PIEffect;',
                  'class RenderEffectDefinition;', 'class PrimeResourceManager;', '', 'enum ResourceId {']
    h += ['\t%s_ID,' % rid for rid in ids]
    h += ['\tRESOURCE_ID_MAX', '};', '',
          '// 0x51d7e0 (zumasrevenge): gives each global to the manager, which sets it whenever its resource loads, and takes',
          '// each image\'s offset. The manifest must be parsed.',
          'void RegisterResourceGlobals(PrimeResourceManager* theManager);',
          'int GetImageOffsetX(int theId);             // the image\'s x= in resources.xml',
          'int GetImageOffsetY(int theId);',
          'const char* GetStringIdById(int theId);     // 0x51db90 (zumasrevenge)',
          'int GetIdByStringId(const char* theName);   // -1 for none',
          '// 0x50ae20 (zumasrevenge): the group of that name\'s extraction function; false for a group with none',
          'bool ExtractResourcesByName(PrimeResourceManager* theManager, const char* theName);',
          '']
    for g, address in EXTRACTS:
        h.append('bool Extract%sResources(PrimeResourceManager* theManager);  // 0x%x (zumasrevenge)' % (g, address))
    h.append('')
    for k in ['Font', 'Image', 'Sound', 'PopAnim', 'PIEffect', 'RenderEffect']:
        h.append('// %s (%d)' % (k, by_kind[k]))
        h += ['extern %s %s;' % (KINDS[k], rid) for rid in ids if kind[rid] == k]
        h.append('')
    h.append('}  // namespace Sexy')

    c = HEADER + ['#include "Res.h"', '', '#include "AutoCrit.h"', '#include "CritSect.h"', '#include "PrimeResourceManager.h"', '',
                  '#include <cstring>', '#include <map>', '#include <string>', '', 'using namespace Sexy;', '']
    for rid in ids:
        c.append('%s Sexy::%s = %s;' % (KINDS[kind[rid]], rid, '0' if KINDS[kind[rid]] == 'int' else 'nullptr'))
    c += ['', 'namespace {', '',
          '// 0x9ebfa8 (zumasrevenge): the address of each id\'s global',
          'void* const gResources[RESOURCE_ID_MAX] = {']
    c += ['\t&%s,' % rid for rid in ids]
    c += ['};', '',
          'const char* const gResourceNames[RESOURCE_ID_MAX] = {']
    c += ['\t"%s",' % rid for rid in ids]
    c += ['};', '',
          '// 0x9f40b8 (zumasrevenge): each image\'s offset (the original keeps a pointer to the resource\'s, which does not',
          '// change after the manifest is read)',
          'Point gImageOffsets[RESOURCE_ID_MAX];', '',
          '// 0x9fcf48 (zumasrevenge): the lock of the map from each resource got through a getter to its id',
          'CritSect& ResourceIdLock() { static CritSect aLock; return aLock; }',
          'std::map<const void*, int>& ResourceIdMap() { static std::map<const void*, int> aMap; return aMap; }', '',
          'void RecordResourceId(const void* theResource, int theId)',
          '{',
          '\tAutoCrit aLock(ResourceIdLock());',
          '\tResourceIdMap()[theResource] = theId;',
          '}', '']
    for k in ['Image', 'Sound', 'Font', 'PopAnim', 'PIEffect']:
        if k == 'Image':
            body = ['\tImage* anImage = theManager->GetImageThrow(gResourceNames[theId], 0, false);',
                    '\tRecordResourceId(anImage, theId);', '\treturn anImage;']
        elif k == 'Font':
            body = ['\tFont* aFont = theManager->GetFontThrow(gResourceNames[theId], 0);',
                    '\tRecordResourceId(aFont, theId);', '\treturn aFont;']
        elif k == 'Sound':
            body = ['\tint aSound = theManager->GetSoundThrow(gResourceNames[theId]);',
                    '\tRecordResourceId((const void*)(intptr_t)aSound, theId);', '\treturn aSound;']
        else:
            var = 'anAnim' if k == 'PopAnim' else 'anEffect'
            body = ['\t%s* %s = theManager->Get%sThrow(gResourceNames[theId]);' % (k, var, k),
                    '\tRecordResourceId(%s, theId);' % var, '\treturn %s;' % var]
        c += ['%s Get%sThrow(PrimeResourceManager* theManager, int theId)  // 0x%x (zumasrevenge)'
              % (KINDS[k], k, GETTER_ADDRESSES[k]), '{'] + body + ['}', '']
    c += ['}  // namespace', '']

    c += ['void Sexy::RegisterResourceGlobals(PrimeResourceManager* theManager)',
          '{',
          '\tfor (int anId = 0; anId < RESOURCE_ID_MAX; anId++) {',
          '\t\ttheManager->RegisterGlobalPtr(gResourceNames[anId], (void**)gResources[anId]);',
          '\t\tgImageOffsets[anId] = theManager->GetImageOffset(gResourceNames[anId]);',
          '\t}',
          '}', '',
          'int Sexy::GetImageOffsetX(int theId) { return gImageOffsets[theId].mX; }',
          'int Sexy::GetImageOffsetY(int theId) { return gImageOffsets[theId].mY; }',
          'const char* Sexy::GetStringIdById(int theId) { return (unsigned)theId < RESOURCE_ID_MAX ? gResourceNames[theId] : ""; }',
          '',
          '// The original fills a map from the names once (the later of two equal names wins) and looks the name up in it',
          'int Sexy::GetIdByStringId(const char* theName)',
          '{',
          '\tstatic std::map<std::string, int> aMap;',
          '\tif (aMap.empty()) {',
          '\t\tfor (int anId = 0; anId < RESOURCE_ID_MAX; anId++)',
          '\t\t\taMap[gResourceNames[anId]] = anId;',
          '\t}',
          '\tstd::map<std::string, int>::iterator anItr = aMap.find(theName);',
          '\treturn anItr == aMap.end() ? -1 : anItr->second;',
          '}', '']

    count = 0
    for g, address in EXTRACTS:
        c += ['bool Sexy::Extract%sResources(PrimeResourceManager* theManager)  // 0x%x (zumasrevenge)' % (g, address), '{',
              '\tRegisterResourceGlobals(theManager);']
        if g == 'Main':
            c += ['\t// The original makes the seven 3D effects here from the sources in its exe; the 3D mode is to come',
                  '\t// (docs/PORT_PLAN.md, "Rendering")', '\treturn true;', '}', '']
            continue
        calls = exe_calls(exe, address, ids)
        listed = [rid for _, rid in groups[g]]
        if sorted(rid for _, rid in calls) != sorted(listed):
            sys.exit('%s: the exe gets %d resources, the manifest lists %d' % (g, len(calls), len(listed)))
        c.append('\ttry {')
        for k, rid in calls:
            if kind[rid] != k:
                sys.exit('0x%x gets %s as %s, which the manifest has as %s' % (address, rid, k, kind[rid]))
            c.append('\t\t%s = Get%sThrow(theManager, %s_ID);' % (rid, k, rid))
        c += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
        count += len(calls)

    c += ['bool Sexy::ExtractResourcesByName(PrimeResourceManager* theManager, const char* theName)  // 0x50ae20 (zumasrevenge)',
          '{']
    for g, _ in EXTRACTS:
        c += ['\tif (strcmp(theName, "%s") == 0)' % g, '\t\treturn Extract%sResources(theManager);' % g]
    c += ['\treturn false;', '}', '']

    os.makedirs(SRC, exist_ok=True)
    open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='').write('\n'.join(h) + '\n')
    open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    print('%d ids, %d calls in %d extraction functions -> Res.h, Res.cpp' % (len(ids), count, len(EXTRACTS)))


if __name__ == '__main__':
    main()
