#!/usr/bin/env python3
"""Writes src/Res.h and src/Res.cpp, the resource globals of Bejeweled 2, as the exe's own ResGen output has them
(0x5d3ffd-0x5d8b5d): the id of every resource (in the order of resources.xml; the exe's table of the names at 0x5d3ffd and its function that finds a group by
name, 0x5d8b5d, are left out: nothing calls them), one global
per resource (an Image*, an ImageFont* or an int for a sound), and one Extract<Group>Resources function for each
<Resources> group, which loads the group's resources through the ResourceManager in the order the exe does (sorted by
name within a group). Also writes re/bejeweled2/res_map.txt, the address of each global and its name, for reading the
export. The ids are identifiers, not text.

    python games/bejeweled2/tools/resgen.py
Reads the export in re/bejeweled2/gn (or gh; tools/ghidra_import.sh) and the exe in re/bejeweled2/bin.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
GH = os.path.join(ROOT, 're', 'bejeweled2', 'gn')
if not os.path.isdir(os.path.join(GH, 'decomp')) or not os.listdir(os.path.join(GH, 'decomp')):
    GH = os.path.join(ROOT, 're', 'bejeweled2', 'gh')
EXE = os.path.join(ROOT, 're', 'bejeweled2', 'bin', 'Bejeweled2Game.exe')
XML = os.path.join(ROOT, 'assets', 'bejeweled2', 'properties', 'resources.xml')
NAME_TABLE_FN = '005d3ffd'
GLOBAL_TABLE = 0x66b7a8   # PTR_DAT_0066b7a8: the address of each id's global
GROUPS = [('3dImages', '005d4aa5'), ('Init', '005d4cda'), ('InitialMainMenu', '005d4e24'), ('LoadScreen', '005d50a2'),
          ('LoadingThread', '005d5369'), ('NonResize', '005d7f7e'), ('Sounds', '005d81b3')]
KINDS = {'image': 'Image*', 'font': 'Font*', 'sound': 'int'}
GETTER = {'image': 'GetImageThrow', 'font': 'GetFontThrow', 'sound': 'GetSoundThrow'}
HEADER = ['// Generated by games/bejeweled2/tools/resgen.py from the exe\'s resource id table (0x5d3ffd) and its group',
          '// functions (0x5d4aa5-0x5d8b5d): the resource globals and their ids, as the exe\'s ResGen output has them.',
          '// The ids are the names of the resources in properties/resources.xml.']


def decomp(addr):
    for sub in os.listdir(os.path.join(GH, 'decomp')):
        d = os.path.join(GH, 'decomp', sub)
        for fn in os.listdir(d):
            if fn.startswith(addr + '_'):
                return open(os.path.join(d, fn), encoding='utf-8', errors='replace').read()
    sys.exit('no decompilation of ' + addr)


def va_to_off(d, va):
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from('<IIII', d, s + i * 40 + 8)
        if rva <= va - base < rva + min(vs, rs):
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ids = []
    for m in re.finditer(r'case (0x[0-9a-f]+|\d+):\s*return "([A-Z0-9_]+)";', decomp(NAME_TABLE_FN)):
        assert int(m.group(1), 0) == len(ids)
        ids.append(m.group(2))
    d = open(EXE, 'rb').read()
    addrs = [struct.unpack_from('<I', d, va_to_off(d, GLOBAL_TABLE + 4 * i))[0] for i in range(len(ids))]
    # the groups and their members come from resources.xml (the exe's LoadingThread group is too big for the
    # decompiler); the exe loads each group's members sorted by name, which the groups that do decompile prove
    xml = open(XML, encoding='utf-8-sig', errors='replace').read()
    prefix = {'Image': 'IMAGE_', 'Font': 'FONT_', 'Sound': 'SOUND_'}
    xml_groups = {}
    for m in re.finditer(r'<Resources\s+id="([^"]+)"\s*>(.*?)</Resources>', xml, re.S):
        xml_groups[m.group(1)] = sorted((prefix[t] + n, t.lower()) for t, n in
                                        re.findall(r'<(Image|Font|Sound)\s+id="([^"]+)"', m.group(2)))
    kind = {}
    groups = []
    for g, fa in GROUPS:
        items = [(k, n) for n, k in xml_groups[g]]
        text = decomp(fa)
        seen = re.findall(r'FUN_00422f60\("([A-Z0-9_]+)"\)', text)
        if seen and seen != [n for _, n in items]:
            sys.exit('%s: the exe loads %s but resources.xml sorted gives %s' % (g, seen[:3], [n for _, n in items][:3]))
        for k, name in items:
            if kind.setdefault(name, k) != k:
                sys.exit('%s is both %s and %s' % (name, kind[name], k))
        groups.append((g, items))
    total = sum(len(i) for _, i in groups)
    if total != len(ids) or set(kind) != set(ids):
        sys.exit('%d ids but %d loaded; only in the table: %s' % (len(ids), total, sorted(set(ids) - set(kind))[:5]))

    h = HEADER + ['#pragma once', '', 'namespace Sexy {', '', 'class Image;', 'class Font;', 'class ResourceManager;', '',
                  'enum ResourceId {']
    h += ['\t%s_ID,' % rid for rid in ids]
    h += ['\tRESOURCE_ID_MAX', '};', '',
          'Image* GetImageById(int theId);               // 0x5d3fca: the global of an image id (null for a font or sound id)', '']
    c = HEADER + ['#include "Res.h"', '', '#include "ResourceManager.h"', '#include "Font.h"', '',
                  'using namespace Sexy;', '']
    for rid in ids:
        c.append('%s Sexy::%s = %s;' % (KINDS[kind[rid]], rid, '0' if kind[rid] == 'sound' else 'nullptr'))
    c += ['', 'Image* Sexy::GetImageById(int theId)', '{', '\tstatic Image** const aImages[RESOURCE_ID_MAX] = {']
    c += ['\t\t%s,' % (('&' + rid) if kind[rid] == 'image' else 'nullptr') for rid in ids]
    c += ['\t};', '\treturn (unsigned)theId < RESOURCE_ID_MAX && aImages[theId] != nullptr ? *aImages[theId] : nullptr;', '}', '']
    for g, items in groups:
        h.append('// %s: 0x%x' % (g, int(dict(GROUPS)[g], 16)))   # the group's function in the exe (the coverage check finds it by this address)
        h.append('bool Extract%sResources(ResourceManager* theManager);' % g)
        for k, rid in items:
            h.append('extern %s %s;' % (KINDS[k], rid))
        h.append('')
        c += ['bool Sexy::Extract%sResources(ResourceManager* theManager)' % g, '{', '\ttry {']
        for k, rid in items:
            c.append('\t\t%s = theManager->%s("%s");' % (rid, GETTER[k], rid))
        c += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
    h.append('}  // namespace Sexy')
    open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='').write('\n'.join(h) + '\n')
    open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    with open(os.path.join(ROOT, 're', 'bejeweled2', 'res_map.txt'), 'w') as f:
        for rid, a in zip(ids, addrs):
            f.write('%08x %s\n' % (a, rid))
    print('%d resources in %d groups; Res.h, Res.cpp, res_map.txt written' % (len(ids), len(groups)))


main()
