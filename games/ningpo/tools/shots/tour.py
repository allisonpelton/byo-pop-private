def port_line(u, s, out):
    c = s[0]
    if c == 'click':
        return '%d click game %d %d' % (u, s[1], s[2])
    if c == 'done':
        return '%d click game %d %d' % ((u,) + DONE['port'])
    if c == 'shot':
        return '%d screenshot %s' % (u, os.path.abspath(os.path.join(out, 'port', s[1] + '.png')).replace('\\', '/'))
    if c == 'focus':
        return '%d focus %s' % (u, 'lost' if s[1] == 'lose' else 'gained')
    if c == 'key':
        return '%d key %s' % (u, s[1])
    if c == 'char':  # its text alone, as the game reads a character (the cheat's letters, the name)
        return '%d text %s' % (u, s[1])
    return '%d quit' % u


def orig_line(s):
    c = s[0]
    if c == 'click':
        return 'click %d %d' % (s[1], s[2])
    if c == 'done':
        return 'click %d %d' % DONE['orig']
    if c == 'shot':
        return 'shot ' + s[1]
    if c == 'focus':
        return 'focus ' + s[1]
    if c == 'key':
        return 'key %d' % VK[s[1]]
    if c == 'char':
        return 'text ' + s[1]
    return 'quit'


WEB_HEAD = """// Generated by games/ningpo/tools/shots/tour.py --web: the screen tour's steps (tour.py's STEPS) on the player-only
// page, each at its update (held there by t.step), its shots in build/webshots/<run>/ for tools/shotdiff against the
// native port's (tour.py's port.txt). Opened with ?player=1&silent=1&assets=1&fast=1&hold=1&run=shots
// &driver=games/ningpo/tools/web/shots.js
var STEPS = %s;
// A hidden Browser pane slows timers and frames down to a few a second; a message to itself is not slowed, so the
// game's sleep (NingPoApp.cpp, ningpo_sleep) yields through one
(function () {
  var ch = new MessageChannel(), due = [];
  ch.port1.onmessage = function () { var f = due.shift(); if (f) f(); };
  Module.ningpoSetTimeout = function (f) { due.push(f); ch.port2.postMessage(0); };
})();
// the native run's -seed=7, through the test command that does the same (README.md, "The standard test commands")
await t.command("seed 7");
var shots = [];
for (var i = 0; i < STEPS.length; i++) {
  var s = STEPS[i], left = s[0] - t.updates() - (STEPS[i][1] === "shot" ? 1 : 0);
  if (left > 0) await t.step(left);
  if (s[1] === "click") await t.click(s[2], s[3]);
  else if (s[1] === "shot") {
    // the redraw (a test command, so it takes the step's update) draws the picture as the native screenshot does
    await t.command("redraw");
    var st = await t.state();
    await t.shot(s[2]);
    shots.push(s[2] + "@" + t.updates() + " " + st.screen + "/" + st.dialog);
  }
  else if (s[1] === "focus" && s[2] === "lose") await t.blur();
  else if (s[1] === "focus") {
    await t.focus();
    // a press within 150 ms of the focus coming back is the click that activates the page (framework/SexyAppBase.cpp,
    // mActivationClickPending); natively the click comes from no focus change
    await new Promise(function (r) { setTimeout(r, 200); });
  } else if (s[1] === "key") await t.key(s[2] === "Return" ? "Enter" : s[2]);
  else if (s[1] === "char") await t.key(s[2], s[2] !== s[2].toLowerCase() ? { shift: true } : null);
  else if (s[1] === "quit") break;
}
t.resume();
return { shots: shots, updates: t.updates() };
"""


def web_steps():
    out = []
    for u, *s in STEPS:
        if s[0] == 'done':
            s = ['click'] + list(DONE['port'])
        out.append([u] + list(s))
    return out


def main():
    if sys.argv[1] == '--web':
        import json
        here = os.path.dirname(os.path.abspath(__file__))
        p = os.path.join(here, '..', 'web', 'shots.js')
        open(p, 'w', newline=chr(10)).write(WEB_HEAD % json.dumps(web_steps()))
        return
    out = sys.argv[1]
    os.makedirs(os.path.join(out, 'port'), exist_ok=True)
    port, orig, prev = [], [], 0
    for u, *s in STEPS:
        port.append(port_line(u, s, out))
        if u > prev:
            orig.append('wait %d' % ((u - prev) * 10 + (1 if prev else 0)))
        prev = u
        orig.append(orig_line(s))
    open(os.path.join(out, 'port.txt'), 'w', newline='\n').write('\n'.join(port) + '\n')
    open(os.path.join(out, 'orig.txt'), 'w', newline='\n').write('\n'.join(orig) + '\n')


if __name__ == '__main__':
    main()
