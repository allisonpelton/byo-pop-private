#!/usr/bin/env python3
"""Generate games/ningpo/src/SpriteTable.inc: the game's table of sprites, index and file name in ningpo.pyz.

The app's constructor (0x4010a0) calls 0x401330, which fills a table at app+0xa914 of 118 pairs {sprite, file
name}: entry i points to the i-th sprite object (app+0x825c + 0x54*i), and the game names a sprite by its index
(getSprite, 0x405af0). Most entries are set one by one, four runs from arrays of names in .data. This reads the
assignments from the decompilation of 0x401330 and the arrays from the exe. The output holds file names only.

    python games/ningpo/tools/make_spritetable.py [--exe re/ningpo/bin/Ningpo.exe] [--out games/ningpo/src/SpriteTable.inc]
"""
import argparse
import glob
import os
import re
import struct

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
TABLE = 0xa914
SPRITES = 0x825c
COUNT = 0x76
# the trial's sprites: the "full version only" signs on the title and its buy button
TRIAL = (14, 15, 74, 75)


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + rs:
            return ro + va - base - rva
    raise ValueError(hex(va))


def cstr(d, va):
    o = va_to_off(d, va)
    return d[o:d.index(b"\0", o)].decode("latin-1")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "ningpo", "bin", "Ningpo.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "ningpo", "src", "SpriteTable.inc"))
    args = ap.parse_args()
    d = open(args.exe, "rb").read()
    src = open(glob.glob(os.path.join(ROOT, "re", "ningpo", "gh", "decomp", "*", "00401330_*.c"))[0]).read()
    names = {}
    # *(int *)(param_1 + T) = param_1 + S;  *(char **)(param_1 + T+4) = "name";  (offsets in hex or decimal)
    num = r"(0x[0-9a-f]+|\d+)"
    slots = {int(t, 0): int(s, 0) for t, s in
             re.findall(r"\*\(int \*\)\(param_1 \+ " + num + r"\) = param_1 \+ " + num + ";", src)}
    # the names are labels of the strings: s_gameover_np_jpg_<address>
    for t, a in re.findall(r"\*\(char \*\*\)\(param_1 \+ " + num + r"\) = (?:PTR_)?s_\w+?_([0-9a-f]{8});", src):
        t = int(t, 0) - 4
        assert slots[t] == SPRITES + 0x54 * ((t - TABLE) // 8), hex(t)
        names[(t - TABLE) // 8] = cstr(d, int(a, 16))
    # the runs: ppuVar2 = &PTR_s_..._<array>; piVar3 = (param_1 + T); iVar4 = param_1 + S; ... while (ppuVar2 < END)
    for m in re.finditer(r"ppuVar2 = &PTR_\w+?_([0-9a-f]{8});|piVar3 = \(int \*\)\(param_1 \+ " + num + r"\);|"
                         r"while \(\(int\)ppuVar2 < 0x([0-9a-f]+)\);", src):
        if m.group(1):
            arr = int(m.group(1), 16)
        elif m.group(2):
            tab = int(m.group(2), 0)
        else:
            end = int(m.group(3), 16)
            for k in range((end - arr) // 4):
                p = struct.unpack_from("<I", d, va_to_off(d, arr + 4 * k))[0]
                names[(tab - TABLE) // 8 + k] = cstr(d, p)
    # Sprites 8 (the arena's background, 0x404ad0) and 117 (the tile set's sheet, 0x404a60) get their files at run
    # time, from the player's choices; the table has no name for them
    missing = [i for i in range(COUNT) if i not in names]
    assert missing == [8, 117], missing
    with open(args.out, "w", newline="\n") as f:
        f.write("// Generated by games/ningpo/tools/make_spritetable.py from 0x401330: the game's sprites by index\n")
        f.write("// (app+0xa914), the file of each in ningpo.pyz. File names only.\n")
        for i in range(COUNT):
            if i in TRIAL:  # the port plays as registered and loads none of the trial's sprites
                f.write('/* %3d */ "",  // the trial\'s %s, left out\n' % (i, names[i]))
            else:
                f.write('/* %3d */ "%s",\n' % (i, names.get(i, "")))
    print("wrote %d sprites to %s" % (COUNT, args.out))


if __name__ == "__main__":
    main()
