#!/usr/bin/env python3
"""Writes src/Res.h and src/Res.cpp, the resource globals of Bookworm Adventures Volume 2, from the game's
properties/resources.xml in the staged files: one Extract<Group>Resources function per <Resources> group, which
fetches each resource by its id (idprefix of the group's last SetDefaults + the element's id) with
ResourceManager::GetImageThrow, GetFontThrow or GetSoundThrow and stores it in a global, and ExtractResourcesByName.
PopCap's ResGen made the exe's the same way from the same file. The ids are identifiers, not text.

    python games/bookwormadv2/tools/resgen.py [assets/bookwormadv2/properties/resources.xml]
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
KINDS = {'Image': ('Image*', 'GetImageThrow', 'nullptr'), 'Font': ('Font*', 'GetFontThrow', 'nullptr'),
         'Sound': ('int', 'GetSoundThrow', '0')}

# The trial's resources are left out: its "buy now" upsell group and the voice that went with it (registration code is
# removed from the ports, not disabled).
OMITTED_GROUPS = {'UpsellTrailer'}
OMITTED_IDS = {'SOUND_MM_BUY_NOW'}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets', 'bookwormadv2', 'properties', 'resources.xml')
    text = open(path, encoding='utf-8-sig').read()
    groups = []  # (name, [(kind, global id)])
    for res in ET.fromstring(text).iter('Resources'):
        if res.get('id') in OMITTED_GROUPS:
            continue
        prefix = ''
        items = []
        for e in res:
            if e.tag == 'SetDefaults':
                prefix = e.get('idprefix', prefix)
            elif e.tag in KINDS and prefix + e.get('id') not in OMITTED_IDS:
                items.append((e.tag, prefix + e.get('id')))
        groups.append((res.get('id'), items))
    seen = {}
    for g, items in groups:
        for kind, rid in items:
            if rid in seen and seen[rid] != kind:
                sys.exit('%s is both %s and %s' % (rid, seen[rid], kind))
            seen[rid] = kind

    h = ['// Generated by games/bookwormadv2/tools/resgen.py from properties/resources.xml: the resource globals of the',
         '// Extract<Group>Resources functions and ExtractResourcesByName, as PopCap\'s ResGen made them. The ids are the',
         '// names of the resources in that file.', '#pragma once', '', 'namespace Sexy {', '',
         'class Image;', 'class Font;', 'class ResourceManager;', '',
         'bool ExtractResourcesByName(ResourceManager* theManager, const char* theName);', '']
    c = ['// Generated by games/bookwormadv2/tools/resgen.py from properties/resources.xml: the resource globals of the',
         '// Extract<Group>Resources functions and ExtractResourcesByName, as PopCap\'s ResGen made them. The ids are the',
         '// names of the resources in that file.', '#include "Res.h"', '', '#include <cstring>', '',
         '#include "ResourceManager.h"', '', 'using namespace Sexy;', '', 'bool gNeedRecalcVariableToIdMap = false;', '']
    done = set()
    for g, items in groups:
        h.append('// %s' % g)
        h.append('bool Extract%sResources(ResourceManager* theManager);' % g)
        for kind, rid in items:
            if rid in done:
                continue
            done.add(rid)
            t, _, init = KINDS[kind]
            h.append('extern %s %s;' % (t, rid))
            c.append('%s Sexy::%s = %s;' % (t, rid, init))
        h.append('')
    h.append('}  // namespace Sexy')
    c.append('')
    for g, items in groups:
        c += ['bool Sexy::Extract%sResources(ResourceManager* theManager)' % g, '{',
              '\tgNeedRecalcVariableToIdMap = true;', '\tResourceManager& aMgr = *theManager;', '\ttry {']
        for kind, rid in items:
            c.append('\t\t%s = aMgr.%s("%s");' % (rid, KINDS[kind][1], rid))
        c += ['\t} catch (ResourceManagerException&) {', '\t\treturn false;', '\t}', '\treturn true;', '}', '']
    c += ['bool Sexy::ExtractResourcesByName(ResourceManager* theManager, const char* theName)', '{']
    for g, _ in groups:
        c += ['\tif (strcmp(theName, "%s") == 0)' % g, '\t\treturn Extract%sResources(theManager);' % g]
    c += ['\treturn false;', '}', '']
    open(os.path.join(SRC, 'Res.h'), 'w', encoding='utf-8', newline='').write('\n'.join(h) + '\n')
    open(os.path.join(SRC, 'Res.cpp'), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    print('%d resources in %d groups -> Res.h, Res.cpp' % (len(done), len(groups)))


if __name__ == '__main__':
    main()
