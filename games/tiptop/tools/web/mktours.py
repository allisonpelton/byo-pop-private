#!/usr/bin/env python3
"""Writes tours.js: the phase-two tours (../shots/tour<N>.txt) as one JS object, because the test server serves only .js files of
a game's tools folder (tools/webtest/serve.py). tour.js reads it. Run it again after a tour changes."""
import glob, json, os
here = os.path.dirname(os.path.abspath(__file__))
tours = {}
for f in sorted(glob.glob(os.path.join(here, "..", "shots", "tour*.txt"))):
    n = os.path.basename(f)[4:-4]
    tours[n] = open(f, encoding="utf-8").read()
with open(os.path.join(here, "tours.js"), "w", encoding="utf-8", newline="\n") as out:
    out.write("// generated by mktours.py from ../shots/tour*.txt\nvar TOURS = " + json.dumps(tours, indent=1) + ";\n")
print("tours.js:", ", ".join(sorted(tours)))
