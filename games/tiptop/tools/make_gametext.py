#!/usr/bin/env python3
"""Generate games/tiptop/src/GameTextTable.inc: where each of TipTop's hard-coded strings is in the exe.

The port carries no game text (games/tiptop/src/GameText.h): it reads every string from the player's own
TipTop.exe by address. This finds those addresses. The input is Ghidra's string export of the game image
(re/tiptop/gh/strings.jsonl, git-ignored: it holds game text) and its decompilation (for the strings Ghidra did
not mark); the output holds only addresses, lengths and hashes. Every string of .rdata and .data is listed, so a
translation can name any of them as GT(0xADDR).

    python games/tiptop/tools/make_gametext.py [--strings re/tiptop/gh/strings.jsonl] [--exe re/tiptop/bin/TipTop.exe]
        [--out games/tiptop/src/GameTextTable.inc]
"""
import argparse
import glob
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
FIRST = 0x46c000   # .rdata and .data
LAST = 0x48d000
RDATA = 0x46c000
RDATA_END = 0x477000


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + rs:  # not past the file's raw data (zero-filled variables)
            return ro + va - base - rva
    raise ValueError(hex(va))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strings", default=os.path.join(ROOT, "re", "tiptop", "gh", "strings.jsonl"))
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "tiptop", "bin", "TipTop.exe"))
    ap.add_argument("--out", default=os.path.join(ROOT, "games", "tiptop", "src", "GameTextTable.inc"))
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    rows = []
    for line in open(args.strings):
        j = json.loads(line)
        if j["type"] != "string":
            continue
        va = int(j["addr"], 16)
        if FIRST <= va < LAST:
            try:
                va_to_off(d, va)
            except ValueError:  # a variable Ghidra typed as a string, not in the file
                continue
            rows.append(va)
    # strings Ghidra did not mark (referenced as DAT_<address> in its decompilation of the game code)
    decomp = os.path.join(os.path.dirname(args.strings), "decomp")
    known = set(rows)
    if os.path.isdir(decomp):
        for path in glob.glob(os.path.join(decomp, "*", "*.c")):
            for m in re.finditer(r"(?:DAT|s_\w*?)_(004[678][0-9a-f]{4})\b", open(path, encoding="latin1").read()):
                va = int(m.group(1), 16)
                if FIRST <= va < LAST and va not in known:
                    try:
                        o = va_to_off(d, va)
                    except ValueError:
                        continue
                    e = d.find(bytes(1), o)
                    s = d[o:e]
                    if 1 <= len(s) < 200 and all(32 <= c < 127 or c in (9, 10, 13) for c in s):
                        rows.append(va)
                        known.add(va)
    # and the literals Ghidra printed inline: every address of a printable string that the code pushes or loads
    # (a 32-bit value anywhere in the image)
    for i in range(len(d) - 3):
        va = struct.unpack_from("<I", d, i)[0]
        if not (RDATA <= va < RDATA_END) or va in known:
            continue
        o = va_to_off(d, va)
        e = d.find(bytes(1), o)
        s = d[o:e]
        if 1 <= len(s) < 200 and all(32 <= c < 127 or c in (9, 10, 13) for c in s):
            rows.append(va)
            known.add(va)
    rows.sort()
    out = ["// Generated by games/tiptop/tools/make_gametext.py. TipTop Deluxe's hard-coded strings: address in the",
           "// game image, length and FNV-1a hash. The texts themselves are read from the player's own TipTop.exe",
           "// at start-up (GameText.h); none are in the repository."]
    for va in rows:
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    open(args.out, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %d entries to %s" % (len(rows), args.out))


if __name__ == "__main__":
    sys.exit(main())
