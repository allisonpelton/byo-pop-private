#!/usr/bin/env python3
"""Generate games/heavyweapon/src/GameTextTable.inc: where each of Heavy Weapon's hard-coded texts is in the game image.

The port carries none of the game's texts (games/heavyweapon/src/GameText.h) and reads them from the player's own
executable by address. The addresses are the ones the source names with GT(0x...), GTC(0x...) or GTA(0x...): this script collects
them from games/heavyweapon/src, reads each text from the game image (re/heavyweapon/bin/HeavyWeaponGame.exe) and writes
only its address, length and hash.

    python games/heavyweapon/tools/make_gametext.py [--exe re/heavyweapon/bin/HeavyWeaponGame.exe] [--check]

--check exits 1, writing nothing, when the table is not the one the source asks for (a GT address added or removed).
"""
import argparse
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(ROOT, "games", "heavyweapon", "src")
OUT = os.path.join(SRC, "GameTextTable.inc")
USE = re.compile(r"\bGT[CA]?\(\s*0x([0-9a-fA-F]{6,8})\s*\)")


def fnv1a(data):
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def va_to_off(d, va):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    s = pe + 24 + opt
    for i in range(nsec):
        vs, rva, rs, ro = struct.unpack_from("<IIII", d, s + i * 40 + 8)
        if rva <= va - base < rva + rs:
            return ro + va - base - rva
    raise ValueError(hex(va))


def used_addresses():
    found = set()
    for folder, _dirs, files in os.walk(SRC):
        for name in files:
            if name.endswith((".cpp", ".h")):
                text = open(os.path.join(folder, name), encoding="utf-8").read()
                found.update(int(m.group(1), 16) for m in USE.finditer(text))
    return sorted(found)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.path.join(ROOT, "re", "heavyweapon", "bin", "HeavyWeaponGame.exe"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    d = open(args.exe, "rb").read()
    out = ["// Generated by games/heavyweapon/tools/make_gametext.py from the GT(0x...) addresses in src. Heavy Weapon",
           "// Deluxe's hard-coded strings: address in the game image, length and FNV-1a hash. The texts themselves are read",
           "// from the player's own executable at start-up (GameText.h); none are in the repository."]
    for va in used_addresses():
        o = va_to_off(d, va)
        e = d.index(b"\0", o)
        s = d[o:e]
        out.append("GAMETEXT(0x%08x, %d, 0x%08x)" % (va, len(s), fnv1a(s)))
    text = "\n".join(out) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if args.check:
        if old != text:
            print("GameTextTable.inc is out of date: run games/heavyweapon/tools/make_gametext.py")
            return 1
        return 0
    if old != text:
        open(OUT, "w", newline="\n").write(text)
    print("%d texts in %s" % (len(out) - 3, OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
