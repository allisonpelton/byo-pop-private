int main()
{
	int aChecks = 0;
	int aFailed = 0;
	auto Check = [&](bool theOk, int theCase, const char* theWhat) {
		aChecks++;
		if (!theOk)
		{
			aFailed++;
			printf("case %d: %s differs\n", theCase, theWhat);
		}
	};

	int aCaseNum = 0;
	for (const GeomCase& k : gCases)
	{
		DisplayGeometry g;
		g.mWidth = k.mIn[0];
		g.mHeight = k.mIn[1];
		g.mDisplayWidth = g.mWidth;
		g.mDisplayHeight = g.mHeight;
		g.mPresentationRect = Rect(0, 0, g.mWidth, g.mHeight);
		int aScale = g.UpdateDisplaySize(k.mIn[2], k.mIn[3], k.mIn[4], k.mIn[5], k.mIn[6]);
		Check((g.mDisplayWidth == k.mDisplay[0]) && (g.mDisplayHeight == k.mDisplay[1]), aCaseNum, "drawable size");
		Check((g.mPresentationRect.mX == k.mPresentation[0]) && (g.mPresentationRect.mY == k.mPresentation[1]) &&
			(g.mPresentationRect.mWidth == k.mPresentation[2]) && (g.mPresentationRect.mHeight == k.mPresentation[3]),
			aCaseNum, "presentation rectangle");
		Check(aScale == k.mRenderScale, aCaseNum, "render scale");
		for (const auto& p : k.mWindowToLogical)
		{
			int x, y;
			g.WindowToLogical(k.mIn[7], k.mIn[8], p[0], p[1], &x, &y);
			Check((x == p[2]) && (y == p[3]), aCaseNum, "WindowToLogical");
		}
		for (const auto& p : k.mLogicalToWindow)
		{
			int x, y;
			g.LogicalToWindow(k.mIn[7], k.mIn[8], p[0], p[1], &x, &y);
			Check((x == p[2]) && (y == p[3]), aCaseNum, "LogicalToWindow");
		}
		for (const auto& c : k.mCursor)
		{
			float x, y, w, h;
			g.CursorRect((int) c[0], (int) c[1], (int) c[2], (int) c[3], &x, &y, &w, &h);
			Check((x == c[4]) && (y == c[5]) && (w == c[6]) && (h == c[7]), aCaseNum, "cursor rectangle");
		}
		aCaseNum++;
	}

	printf("geometry: %d cases, %d checks, %d failed\n", aCaseNum, aChecks, aFailed);
	return (aFailed == 0) ? 0 : 1;
}
