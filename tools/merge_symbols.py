#!/usr/bin/env python3
"""Merge symbol identifications (workflow results) into a Ghidra ApplySymbols JSON-lines file.

    python tools/merge_symbols.py <workflow-output.json> re/symbols/10_framework.jsonl [--notes docs/FRAMEWORK_NOTES.md]

The input is the JSON written by a Workflow run whose result is a list of
{key, symbols:[{addr,name,sig,confidence,evidence}], notes}. Conflicting names for one address are
resolved by confidence (high > medium > low), then by first occurrence; conflicts are reported.
"""
import argparse
import json
import re
import sys

RANK = {"high": 3, "medium": 2, "low": 1}


def load_groups(path):
    data = json.load(open(path, encoding="utf-8"))
    result = data.get("result", data)
    if isinstance(result, dict) and "groups" in result:
        result = result["groups"]
    if not isinstance(result, list):
        sys.exit("unexpected workflow result shape")
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("workflow_output")
    ap.add_argument("out")
    ap.add_argument("--notes")
    args = ap.parse_args()

    groups = load_groups(args.workflow_output)
    best = {}
    conflicts = []
    for g in groups:
        for s in g.get("symbols", []):
            addr = s.get("addr", "").lower().replace("0x", "").zfill(8)
            if not re.fullmatch(r"[0-9a-f]{8}", addr):
                continue
            name = s.get("name", "").strip()
            if not name:
                continue
            rank = RANK.get(s.get("confidence", "low"), 1)
            cur = best.get(addr)
            if cur and cur["name"] != name:
                conflicts.append((addr, cur["name"], cur["confidence"], name, s.get("confidence"), g.get("key")))
            if not cur or rank > RANK.get(cur["confidence"], 1):
                best[addr] = {"name": name, "sig": s.get("sig", ""), "confidence": s.get("confidence", "low"),
                              "group": g.get("key")}

    with open(args.out, "w", encoding="utf-8") as f:
        for addr in sorted(best):
            b = best[addr]
            rec = {"addr": addr, "name": b["name"].replace(" ", "_") if " " in b["name"] and "::" not in b["name"] else b["name"]}
            # Ghidra names can't contain spaces/quotes; keep template brackets.
            rec["name"] = re.sub(r"[\s'`]", "_", rec["name"])
            if b["sig"] and b["confidence"] != "low":
                rec["sig"] = b["sig"]
            rec["comment"] = f"[{b['confidence']}] identified by {b['group']}"
            f.write(json.dumps(rec) + "\n")
    print(f"{len(best)} symbols -> {args.out}; {len(conflicts)} conflicts")
    for c in conflicts[:50]:
        print("  conflict", c)

    if args.notes:
        with open(args.notes, "w", encoding="utf-8") as f:
            f.write("# Framework identification notes\n\nGenerated by tools/merge_symbols.py from the identification workflow.\n\n")
            for g in groups:
                f.write(f"## {g.get('key')}\n\n{g.get('notes', '').strip()}\n\n")


if __name__ == "__main__":
    main()
